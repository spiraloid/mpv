        for i = 1, #pts, 2 do seq[#seq + 1] = {x0 + pts[i] * s, y0 + pts[i + 1] * s} end
        for i = #seq - 1, 1, -1 do seq[#seq + 1] = seq[i] end   -- and back again
        out[#out + 1] = string.format("m %.1f %.1f", seq[1][1], seq[1][2])
        for i = 2, #seq do out[#out + 1] = string.format("l %.1f %.1f", seq[i][1], seq[i][2]) end
    end
    return table.concat(out, " ")
end

local function circle_path(cx, cy, r)
    local c = 0.5523 * r
    return string.format("m %.1f %.1f b %.1f %.1f %.1f %.1f %.1f %.1f b %.1f %.1f %.1f %.1f %.1f %.1f " ..
                         "b %.1f %.1f %.1f %.1f %.1f %.1f b %.1f %.1f %.1f %.1f %.1f %.1f",
        cx + r, cy, cx + r, cy + c, cx + c, cy + r, cx, cy + r, cx - c, cy + r, cx - r, cy + c, cx - r, cy,
        cx - r, cy - c, cx - c, cy - r, cx, cy - r, cx + c, cy - r, cx + r, cy - c, cx + r, cy)
end

-- Shown only while paused, so playback stays clean (screen shares, recordings)
local function button_events(events, shot, vx0, vy0, vw, k)
    buttons = {}
    local list = mp.get_property_bool("pause") and shot_buttons(shot)
    if not list then return end
    local d, gap = B.size * k, B.gap * k
    local x = vx0 + vw - B.right * k - (#list * d + (#list - 1) * gap)
    local y = vy0 + B.top * k
    local s = B.icon * k / 24                        -- icon scale: 24-unit grid -> pixels
    local inset = (d - B.icon * k) / 2
    for _, b in ipairs(list) do
        local hot = b.enabled and hovered == b.name
        -- approved (disabled) reads as done: solid fill; grayed out (dim) reads as off
        local fill_a = b.dim and "60" or ((hot or not b.enabled) and "00" or "40")
        local icon_a = b.dim and "90" or "00"
        -- every drawing is in absolute OSD pixels, anchored at \pos(0,0)
        events[#events + 1] = string.format(
            "{\\an7\\pos(0,0)\\p1\\bord%.2f\\shad0\\1c&H%s&\\1a&H%s&\\3c&HFFFFFF&\\3a&H%s&}%s{\\p0}",
            hot and 2.5 * k or 0, b.color, fill_a, hot and "00" or "FF", circle_path(x + d / 2, y + d / 2, d / 2))
        if b.filled then  -- approved: the thumb is filled in
            events[#events + 1] = string.format(
                "{\\an7\\pos(0,0)\\p1\\bord0\\shad0\\1c&HFFFFFF&\\1a&H00&}%s{\\p0}",
                icon_fill_path(b.icon, x + inset, y + inset, s))
        end
        events[#events + 1] = string.format(
            "{\\an7\\pos(0,0)\\p1\\bord%.2f\\shad0\\1a&HFF&\\3c&HFFFFFF&\\3a&H%s&}%s{\\p0}",
            s, icon_a, icon_path(b.icon, x + inset, y + inset, s))
        buttons[#buttons + 1] = {name = b.name, x0 = x, y0 = y, x1 = x + d, y1 = y + d, enabled = b.enabled}
        x = x + d + gap
    end
end

local function clear_overlay()
    buttons = {}
    if overlay_key then overlay:remove(); overlay_key = nil end
    if update_hover then update_hover(nil) end
end

local function render(force)
    if export.running or export.prompting then clear_overlay(); return end
    local i = state.assembly and current_shot_index()
    local shot = i and state.shots[i]
    local d = mp.get_property_native("osd-dimensions")
    if not shot or not d or not d.w or d.w <= 0 then clear_overlay(); return end
    local key = table.concat({i, d.w, d.h, d.ml, d.mt, d.mr, d.mb, tostring(hovered),
                              tostring(shot.approved), tostring(approving), tostring(overlay_on),
                              tostring(mp.get_property_bool("pause")), tostring(preview.shown)}, ":")
    if key == overlay_key and not force then return end

    -- video rectangle inside the window (letterbox margins)
    local vx0, vy0 = d.ml, d.mt
    local vw, vh = d.w - d.ml - d.mr, d.h - d.mt - d.mb
    local k = vh / 1080
    local events = {}
    if shot.retired then rejected_events(events, vx0, vy0, vw, vh, k, "REJECTED")
    elseif shot.missing then rejected_events(events, vx0, vy0, vw, vh, k, "MISSING") end
    buttons = {}
    -- a preview still carries its own label; its buttons would act on the real shot
    if overlay_on and not preview.shown then
        label_events(events, shot, vx0, vy0, vw, vh, k)
        button_events(events, shot, vx0, vy0, vw, k)
    end
    if #events == 0 then clear_overlay(); return end
    overlay_key = key
    overlay.res_x, overlay.res_y = d.w, d.h
    overlay.data = table.concat(events, "\n")
    overlay:update()
    -- buttons can appear under a mouse that isn't moving (next shot, reload)
    if update_hover then update_hover(mp.get_property_native("mouse-pos")) end
end

mp.observe_property("time-pos", "number", function() render() end)
mp.observe_property("osd-dimensions", "native", function() render(true) end)
mp.observe_property("pause", "bool", function() render() end)
mp.register_event("end-file", clear_overlay)

-- ── reject (r) ────────────────────────────────────────────────────────────────

local function current_shot()
    local i = current_shot_index()
    return i and state.shots[i]
end

local function retire()
    local asm = state.assembly
    if not asm then osd("r rejects a clip while playing an XML assembly", 2); return end
    if asm.generated then osd("this XML only marks shots of one video; nothing to reject", 2); return end
    local pos = mp.get_property_number("time-pos") or 0
    local shot = current_shot()
    if not shot then return end
    if shot.retired then osd("already rejected: " .. (shot.label or shot.name), 1.5); return end
    local clip = asm.seq.video[shot.idx]
    if asm.review_layout then
        local ri = shot.rung
        if not ri or ri.retired then osd("only clips in a lettered rung folder can be rejected", 2); return end
        if exists(retired_path(ri)) then
            osd(ri.rung .. "/retired/" .. ri.sub .. " already exists; not rejected", 3); return
        end
        if not exists(shot.play) then osd("source missing: " .. tostring(shot.play), 2.5); return end
        pending_action = {
            kind = "reject", review = true, xml = asm.xml, path = shot.play, file_key = clip.file_key,
            pathurl = clip.pathurl, name = shot.label or clip.name, num_text = shot.num_text, pos = pos,
        }
        osd("rejecting " .. (shot.label or clip.name) .. "…", 1)
        mp.commandv("loadfile", state.path, "replace")  -- let go of the file before moving it
        return
    elseif shot.refs > 1 then
        osd(string.format("%s is used %d times in this edit; not rejected", name_of(clip.path), shot.refs), 2.5)
        return
    end
    if not exists(clip.path) then osd("source missing: " .. tostring(clip.path), 2.5); return end
    pending_action = {
        kind = "reject", xml = asm.xml, path = clip.path, file_key = clip.file_key, pathurl = clip.pathurl,
        name = shot.label or clip.name, pos = pos,
    }
    osd("rejecting " .. (shot.label or clip.name) .. "…", 1)
    -- Reload so mpv lets go of the source before it is moved (see do_retire)
    mp.commandv("loadfile", state.path, "replace")
end

-- ── restore (rotate-ccw): undo a reject ───────────────────────────────────────

-- Where a rejected clip lived before it was moved to retired/
local function original_path(asm, path)
    local p = path:gsub("\\", "/")
    local d = dir_of(asm.xml):gsub("\\", "/")
    local rd = d .. "/" .. o.retired_dir .. "/"
    if p:sub(1, #rd) == rd then return native_seps(d .. "/" .. p:sub(#rd + 1)) end
    return path  -- disabled in the XML but never moved: just enable it again
end

local function restore()
    local asm = state.assembly
    if not asm then return end
    local pos = mp.get_property_number("time-pos") or 0
    local shot = current_shot()
    if not shot then return end
    local clip = asm.seq.video[shot.idx]
    if asm.review_layout then
        local ri = shot.rung
        local live = not shot.retired and not shot.missing and shot.play or nil
        local e = ri and next_up(ri.shots, ri.nn, live, {})
        if not e then osd("nothing newer to bring back", 1.5); return end
        pending_action = {
            kind = "restore", review = true, xml = asm.xml, entry = e, shots = ri.shots,
            file_key = clip.file_key, pathurl = clip.pathurl, num_text = shot.num_text, pos = pos,
        }
        osd("bringing back " .. name_of(e.orig_path) .. "…", 1)
        mp.commandv("loadfile", state.path, "replace")  -- let go of files before moving them
        return
    end
    if not shot.retired then osd("not rejected: " .. (shot.label or shot.name), 1.5); return end
    local orig = original_path(asm, clip.path)
    if orig ~= clip.path and exists(orig) then
        osd("a file is already at " .. name_of(orig) .. "'s old place; not restored", 3); return
    end
    if not exists(clip.path) then osd("source missing: " .. tostring(clip.path), 2.5); return end
    pending_action = {
        kind = "restore", xml = asm.xml, path = clip.path, orig = orig, file_key = clip.file_key,
        pathurl = clip.pathurl, name = shot.label or clip.name, pos = pos,
    }
    osd("restoring " .. (shot.label or clip.name) .. "…", 1)
    mp.commandv("loadfile", state.path, "replace")  -- let go of the file first, as for reject
end

-- ── approve (a): copy the candidate to shots/K_final/NN.<ext> ────────────────

-- Copies to a hidden .NN.<ext>.part beside the final and renames when done, so
-- an interrupted copy never sits in K_final looking like a final.
local approve_job   -- {src, part, final} while a copy runs

local function finish_approve_copy(job)
    if exists(job.part) and not exists(job.final) and os.rename(job.part, job.final) then
        session.journal[#session.journal + 1] = {create = job.final}
        return true
    end
    os.remove(job.part)
    return false
end

local function approve()
    local asm = state.assembly
    if not asm then osd("a approves a candidate while playing an XML assembly", 2); return end
    local shot = current_shot()
    if not shot or approving then return end
    if shot.retired then restore(); return end  -- on a rejected slot, a is the undo button
    local ri = shot.rung
    if not ri or ri.retired or shot.missing then
        osd("only clips in a lettered rung folder can be approved", 2); return
    end
    if ri.letter == "K" then osd("this is already a final", 1.5); return end
    local final = final_path(ri)
    if exists(final) then
        shot.approved = true
        render(true)
        osd("shot " .. ri.num .. " already has a final: " .. name_of(final), 2.5)
        return
    end
    local src = shot.play
    if not exists(src) then osd("source missing: " .. tostring(src), 2.5); return end
    if not mkdir_p(dir_of(final)) then osd("approve failed: could not create the finals folder", 3); return end
    local job = {src = src, final = final,
                 part = utils.join_path(dir_of(final), "." .. name_of(final) .. ".part")}
    os.remove(job.part)
    job.args = is_windows
        and {"powershell", "-NoProfile", "-WindowStyle", "Hidden", "-Command",
             "Copy-Item -LiteralPath " .. ps_quote(src) .. " -Destination " .. ps_quote(job.part) .. " -ErrorAction Stop"}
        or {"cp", src, job.part}
    approving, approve_job = true, job
    render(true)
    job.token = mp.command_native_async({name = "subprocess", args = job.args, playback_only = false,
                                         capture_stdout = true, capture_stderr = true},
        function(ok, res)
            if job.finished then return end   -- finished at shutdown instead
            job.finished = true
            approving, approve_job = false, nil
            if ok and res and res.status == 0 and finish_approve_copy(job) then
                shot.approved = true
                msg.info("approved " .. src .. " -> " .. final)
                osd("approved: " .. (shot.label or shot.name) .. "  →  final " .. name_of(final), 2.5)
            else
                msg.error("approve copy failed: " .. tostring(res and res.stderr))
                osd("approve failed: could not copy to K_final", 3)
            end
            render(true)
        end)
end

-- ── mouse: click the buttons ──────────────────────────────────────────────────

local click_bound = false
local function set_click_binding(on)
    if on == click_bound then return end
    click_bound = on
    if on then
        mp.add_forced_key_binding("MBTN_LEFT", "shot_button_click", function()
            update_hover(mp.get_property_native("mouse-pos"))   -- where the pointer is now
            if hovered == "approve" then approve()
            elseif hovered == "restore" then restore()
            elseif hovered == "reject" then retire() end
        end)
        -- keep a quick second click from toggling fullscreen
        mp.add_forced_key_binding("MBTN_LEFT_DBL", "shot_button_dbl", function() end)
    else
        mp.remove_key_binding("shot_button_click")
        mp.remove_key_binding("shot_button_dbl")
    end
end

-- mpv's on-screen controller (osc.lua) grabs MBTN_LEFT whenever it shows, and
-- with no window border it draws minimize / maximize / close in the top-right
-- corner, over these buttons. Whichever input section was enabled last wins the
-- click, so near the buttons the controller is told to stay hidden, and the
-- click binding is put back on top once it has let go.
local osc_hidden = false
local function hide_osc(on)
    if on == osc_hidden then return end
    osc_hidden = on
    mp.commandv("script-message", "osc-visibility", on and "never" or "auto", "no_osd")
    if on and click_bound then          -- re-push our click above the controller's
        click_bound = false
        mp.add_timeout(0.05, function() if hovered then set_click_binding(true) end end)
    end
end

update_hover = function(m)
    local h, near = nil, false
    if m and m.hover and #buttons > 0 then
        local pad = 0
        for _, b in ipairs(buttons) do pad = math.max(pad, b.x1 - b.x0) end
        local x0, y0, x1, y1 = math.huge, math.huge, -math.huge, -math.huge
        for _, b in ipairs(buttons) do
            x0, y0 = math.min(x0, b.x0), math.min(y0, b.y0)
            x1, y1 = math.max(x1, b.x1), math.max(y1, b.y1)
            if b.enabled and m.x >= b.x0 and m.x <= b.x1 and m.y >= b.y0 and m.y <= b.y1 then h = b.name end
        end
        -- the zone around the buttons, up to the top edge where the controls draw
        near = m.x >= x0 - pad and m.x <= x1 + pad and m.y <= y1 + pad
    end
    hide_osc(near)
    set_click_binding(h ~= nil)
    if h ~= hovered then hovered = h; render() end
end

mp.observe_property("mouse-pos", "native", function(_, m) update_hover(m) end)

