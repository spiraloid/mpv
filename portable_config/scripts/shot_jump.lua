local function clear_overlay()
    buttons = {}
    if overlay_key then overlay:remove(); overlay_key = nil end
    if update_hover then update_hover(nil) end
end

local function render(force)
    if export.running or export.prompting then clear_overlay(); return end
    local i = state.assembly and current_shot_index()
    local shot = i and state.shots[i]
    local d = mp.get_property_native("osd-dimensions")
    if not shot or not d or not d.w or d.w <= 0 then clear_overlay(); return end
    local key = table.concat({i, d.w, d.h, d.ml, d.mt, d.mr, d.mb, tostring(hovered),
                              tostring(overlay_on),
                              tostring(mp.get_property_bool("pause"))}, ":")
    if key == overlay_key and not force then return end

    -- video rectangle inside the window (letterbox margins)
    local vx0, vy0 = d.ml, d.mt
    local vw, vh = d.w - d.ml - d.mr, d.h - d.mt - d.mb
    local k = vh / 1080
    local events = {}
    if shot.retired then rejected_events(events, vx0, vy0, vw, vh, k, "REJECTED")
    elseif shot.missing then rejected_events(events, vx0, vy0, vw, vh, k, "MISSING") end
    buttons = {}
    if overlay_on then
        label_events(events, shot, vx0, vy0, vw, vh, k)
        button_events(events, shot, vx0, vy0, vw, k)
    end
    if #events == 0 then clear_overlay(); return end
    overlay_key = key
    overlay.res_x, overlay.res_y = d.w, d.h
    overlay.data = table.concat(events, "\n")
    overlay:update()
    -- buttons can appear under a mouse that isn't moving (next shot, reload)
    if update_hover then update_hover(mp.get_property_native("mouse-pos")) end
end

mp.observe_property("time-pos", "number", function()
    local asm = state.assembly
    local i = asm and current_shot_index()
    -- the looping shot was left some other way (a click on the seek bar): the timeline runs on
    if slack.loop and i and i ~= slack.loop.idx then slack.unloop() end
    -- another shot: the one left goes back to its select (a reload, landing where we are)
    local here = slack.here
    if i and here and here.xml == asm.xml and here.idx ~= i and not pending_action then
        slack.here = {xml = asm.xml, idx = i}
        if slack.snap_back(here.idx) then
            pending_action = {kind = "choose", xml = asm.xml, pos = mp.get_property_number("time-pos")}
            mp.commandv("loadfile", state.path, "replace")
            return
        end
    elseif i then
        slack.here = {xml = asm.xml, idx = i}
    end
    render()
end)
mp.observe_property("osd-dimensions", "native", function() render(true) end)
mp.observe_property("pause", "bool", function() render() end)
mp.register_event("end-file", clear_overlay)

-- ── reject (r) ────────────────────────────────────────────────────────────────

local function current_shot()
    local i = current_shot_index()
    return i and state.shots[i]
end

local function retire()
    local asm = state.assembly
    if not asm then osd("r rejects a clip while playing an XML assembly", 2); return end
    if o.preview then osd("preview: nothing is moved or saved", 2); return end
    if asm.generated then osd("this XML only marks shots of one video; nothing to reject", 2); return end
    local pos = mp.get_property_number("time-pos") or 0
    local shot = current_shot()
    if not shot then return end
    if shot.retired then osd("already rejected: " .. (shot.label or shot.name), 1.5); return end
    local clip = asm.seq.video[shot.idx]
    if asm.review_layout then
        osd("nothing is rejected in a rung layout: step to the version you want and mark it", 3)
        return
    elseif shot.refs > 1 then
        osd(string.format("%s is used %d times in this edit; not rejected", name_of(clip.path), shot.refs), 2.5)
        return
    end
    if not exists(clip.path) then osd("source missing: " .. tostring(clip.path), 2.5); return end
    pending_action = {
        kind = "reject", xml = asm.xml, path = clip.path, file_key = clip.file_key, pathurl = clip.pathurl,
        name = shot.label or clip.name, pos = pos,
    }
    osd("rejecting " .. (shot.label or clip.name) .. "…", 1)
    -- Reload so mpv lets go of the source before it is moved (see do_retire)
    mp.commandv("loadfile", state.path, "replace")
end

-- ── restore (rotate-ccw): undo a reject ───────────────────────────────────────

-- Where a rejected clip lived before it was moved to retired/
local function original_path(asm, path)
    local p = path:gsub("\\", "/")
    local d = dir_of(asm.xml):gsub("\\", "/")
    local rd = d .. "/" .. o.retired_dir .. "/"
    if p:sub(1, #rd) == rd then return native_seps(d .. "/" .. p:sub(#rd + 1)) end
    return path  -- disabled in the XML but never moved: just enable it again
end

local function restore()
    local asm = state.assembly
    if not asm then return end
    if o.preview then osd("preview: nothing is moved or saved", 2); return end
    local pos = mp.get_property_number("time-pos") or 0
    local shot = current_shot()
    if not shot then return end
    local clip = asm.seq.video[shot.idx]
    if asm.review_layout then return end
    if not shot.retired then osd("not rejected: " .. (shot.label or shot.name), 1.5); return end
    local orig = original_path(asm, clip.path)
    if orig ~= clip.path and exists(orig) then
        osd("a file is already at " .. name_of(orig) .. "'s old place; not restored", 3); return
    end
    if not exists(clip.path) then osd("source missing: " .. tostring(clip.path), 2.5); return end
    pending_action = {
        kind = "restore", xml = asm.xml, path = clip.path, orig = orig, file_key = clip.file_key,
        pathurl = clip.pathurl, name = shot.label or clip.name, pos = pos,
    }
    osd("restoring " .. (shot.label or clip.name) .. "…", 1)
    mp.commandv("loadfile", state.path, "replace")  -- let go of the file first, as for reject
end

-- ── mouse: click the buttons ──────────────────────────────────────────────────

-- mpv drags the window when the pointer moves a few pixels with the button held,
-- and a click that turned into a drag never reaches a button. Over a button, and
-- while a prompt is up, the window doesn't drag.
local drag = {holds = {}}
function drag.hold(why, on)
    if on and not next(drag.holds) then drag.was = mp.get_property("window-dragging") end
    drag.holds[why] = on or nil
    if next(drag.holds) then mp.set_property("window-dragging", "no")
    elseif drag.was then mp.set_property("window-dragging", drag.was); drag.was = nil end
end

-- Where the pointer really is, at a click. On the Mac, mpv only learns the pointer's
-- place from mouse-moved events, and for a while after a reload or a prompt
-- opening it may hear none: its mouse-pos stays where the pointer was, and a
-- click lands on whatever used to be there (or nothing). So a click asks macOS
-- (NSEvent.mouseLocation and this window's frame, about 0.1 s) and maps that
-- to the OSD. Elsewhere, and if that fails, mouse-pos.
drag.JXA = [==[
ObjC.import('AppKit'); ObjC.import('CoreGraphics');
function run(argv) {
  var pid = parseInt(argv[0]), loc = $.NSEvent.mouseLocation;
  var H = $.NSScreen.screens.objectAtIndex(0).frame.size.height;
  var list = ObjC.castRefToObject($.CGWindowListCopyWindowInfo($.kCGWindowListOptionOnScreenOnly, $.kCGNullWindowID));
  for (var i = 0; i < list.count; i++) {
    var w = list.objectAtIndex(i);
    if (w.objectForKey('kCGWindowOwnerPID').js == pid && w.objectForKey('kCGWindowLayer').js == 0) {
      var b = w.objectForKey('kCGWindowBounds');
      return [loc.x, H - loc.y, b.objectForKey('X').js, b.objectForKey('Y').js, b.objectForKey('Width').js, b.objectForKey('Height').js].join(' ');
    }
  }
  return '';
}
]==]
function drag.pointer()
    local m = mp.get_property_native("mouse-pos")
    if mp.get_property("platform") ~= "darwin" or not o.real_pointer then return m end
    if not drag.jxa_path then
        drag.jxa_path = utils.join_path(temp_dir(), "mpv-pointer.js")
        write_file(drag.jxa_path, drag.JXA)
    end
    local r = mp.command_native({name = "subprocess", playback_only = false, capture_stdout = true,
                                 capture_stderr = true,
                                 args = {"osascript", "-l", "JavaScript", drag.jxa_path, tostring(utils.getpid())}})
    local v = {}
    for n in ((r and r.status == 0 and r.stdout) or ""):gmatch("%-?[%d%.]+") do v[#v + 1] = tonumber(n) end
    local d = mp.get_property_native("osd-dimensions")
    if #v < 6 or not d or not d.w or v[5] <= 0 or v[6] <= 0 then return m end
    return {x = (v[1] - v[3]) * d.w / v[5], y = (v[2] - v[4]) * d.h / v[6], hover = true}
end

-- Where a click is: mpv's own idea of the pointer when that lands on something
-- (instant), else ask macOS (drag.pointer, a few tenths of a second)
function drag.pointer_on(hits)
    local m = mp.get_property_native("mouse-pos")
    if m and m.hover and hits(m) then return m end
    return drag.pointer()
end

local click_bound = false
local function set_click_binding(on)
    if on == click_bound then return end
    click_bound = on
    if on then
        mp.add_forced_key_binding("MBTN_LEFT", "shot_button_click", function(e)
            if B.box_click then return B.box_click(e) end   -- the note box is open: it takes the click
            if e.event ~= "down" and e.event ~= "press" then return end
            local function on(p)
                local h
                for _, bt in ipairs(buttons) do
                    if bt.enabled and p and p.x >= bt.x0 and p.x <= bt.x1 and p.y >= bt.y0 and p.y <= bt.y1 then h = bt.name end
                end
                return h
            end
            local h = on(drag.pointer_on(on))   -- where the pointer really is now
            if h == "restore" then restore()
            elseif h == "reject" then retire()
            elseif h and review_click then review_click(h) end
        end, {complex = true})
        -- keep a quick second click from toggling fullscreen
        mp.add_forced_key_binding("MBTN_LEFT_DBL", "shot_button_dbl", function() end)
    else
        mp.remove_key_binding("shot_button_click")
        mp.remove_key_binding("shot_button_dbl")
    end
end

-- mpv's on-screen controller (osc.lua) grabs MBTN_LEFT whenever it shows, and
-- with no window border it draws minimize / maximize / close in the top-right
-- corner, over these buttons. Whichever input section was enabled last wins the
-- click, so near the buttons the controller is told to stay hidden, and the
-- click binding is put back on top once it has let go.
local osc_hidden = false
local function hide_osc(on)
    if on == osc_hidden then return end
    osc_hidden = on
    mp.commandv("script-message", "osc-visibility", on and "never" or "auto", "no_osd")
    if on and click_bound then          -- re-push our click above the controller's
        click_bound = false
        -- whenever buttons show, not only when mpv thinks the pointer is on one: on the
        -- Mac its idea of the pointer can be stale, and the controller then took the first click
        mp.add_timeout(0.05, function() if #buttons > 0 and not export.prompting then set_click_binding(true) end end)
    end
end

update_hover = function(m)
    if export.prompting or export.running then   -- a prompt is up: its buttons, and no controller
        if export.prompting and modal_hover then modal_hover(m) end
        return
    end
    local h, near = nil, false
    if m and m.hover and #buttons > 0 then
        local pad = 0
        for _, b in ipairs(buttons) do pad = math.max(pad, b.x1 - b.x0) end
        local x0, y0, x1, y1 = math.huge, math.huge, -math.huge, -math.huge
        for _, b in ipairs(buttons) do
            x0, y0 = math.min(x0, b.x0), math.min(y0, b.y0)
            x1, y1 = math.max(x1, b.x1), math.max(y1, b.y1)
            if b.enabled and m.x >= b.x0 and m.x <= b.x1 and m.y >= b.y0 and m.y <= b.y1 then h = b.name end
        end
        -- the zone around the buttons, up to the top edge where the controls draw
        near = m.x >= x0 - pad and m.x <= x1 + pad and m.y <= y1 + pad
    end
    hide_osc(near)
    -- bound while any button shows, not only when mpv thinks the pointer is on one:
    -- the click itself asks where the pointer is
    drag.hold("button", #buttons > 0)
    set_click_binding(#buttons > 0)
    if h ~= hovered then hovered = h; render() end
end

mp.observe_property("mouse-pos", "native", function(_, m)
    if B.box_move then B.box_move(m) end   -- a drag in the note box
    update_hover(m)
end)

