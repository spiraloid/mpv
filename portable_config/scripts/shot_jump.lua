local function quit_request()
    if export.running then           -- second quit while saving: skip the video
        export.skip = true
        mp.abort_async_command(export.running)
        mp.command("quit")
        return
    end
    if export.prompting then return end
    if pending_action then mp.add_timeout(0.2, quit_request); return end  -- let it land first
    local r = current_review()
    if r and not encoding then            -- a review: only its unsaved choices matter
        if review_busy then return end
        if r.preview then
            -- the editor has gone: Esc takes the review over, right here, instead of quitting
            if not r.preview.view_only and not lock.other(r.xml) and notes.take_over(r) then return end
            mp.command("quit"); return   -- nothing could be saved anyway
        end
        if #review_changes(r) > 0 then open_review_prompt(r) else mp.command("quit") end
        return
    end
    if session_changed() and not encoding then open_prompt() else mp.command("quit") end
end

choose = function(i)
    if i == 1 then                    -- Yes: keep, render the edit if it changed, quit
        export.choice = "yes"
        if export.dirty and not export.done then
            run_export(function() mp.command("quit") end)
        else
            mp.command("quit")
        end
    elseif i == 2 then                -- No: put everything back at shutdown, quit
        export.choice = "no"
        mp.command("quit")
    else                              -- Cancel: back to the player as it was
        render(true)
    end
end

-- The edit's sound, played from a copy on this computer: the edit is a big video
-- on a cloud drive, and reading its sound from there made opening the review take
-- minutes. The first time (and after the edit changes) the copy is made in the
-- background, the XML's audio track plays meanwhile, and the review reloads onto
-- the copy when it's ready. The copies live in mpv's cache folder.
export.sound_file = function(c)
    local info = utils.file_info(c.path)
    if not info or not info.is_file then return nil end
    local key, h = c.path .. "|" .. tostring(info.size) .. "|" .. tostring(info.mtime), 5381
    for i = 1, #key do h = (h * 33 + key:byte(i)) % 4294967296 end
    local dir = mp.command_native({"expand-path", "~~/cache"})
    local out = utils.join_path(dir, string.format("edit-sound-%08x.wav", h))
    if exists(out) then return out end
    if export.sound_making or not mkdir_p(dir) then return nil end
    local tmp = utils.join_path(dir, string.format("edit-sound-%08x.part", h))
    os.remove(tmp)
    export.sound_making = out
    msg.info("copying the edit's sound to " .. out)
    mp.command_native_async({name = "subprocess", playback_only = false, capture_stdout = true, capture_stderr = true,
        args = {mpv_binary(), "--no-config", "--msg-level=all=error", "--vid=no", "--sid=no",
                "--o=" .. tmp, "--of=wav", "--oac=pcm_s16le", "--", c.path}},
        function(ok, res)
            export.sound_making = nil
            if not (ok and res and res.status == 0 and exists(tmp) and os.rename(tmp, out)) then
                os.remove(tmp)
                msg.warn("could not copy the edit's sound: " .. tostring(res and (res.stderr or res.error_string)))
                return
            end
            msg.info("the edit's sound is ready")
            -- reload onto it, unless something is open on screen
            local asm = state.assembly
            if asm and asm.export_sound and export.listen == "export" and not notes.box
               and not export.prompting and not export.running and not review_busy and not pending_action then
                pending_action = {kind = "choose", xml = asm.xml, notice = "the edit's sound is ready",
                                  pos = mp.get_property_number("time-pos") or 0}
                mp.commandv("loadfile", state.path, "replace")
            end
        end)
    return nil
end

local quit_keys = {"ESC", "q", "Q", "CLOSE_WIN", "Meta+q", "Meta+w", "Ctrl+w"}
local quit_bound = false
bind_quit_keys = function(on)
    if on == quit_bound or encoding then return end
    quit_bound = on
    for _, key in ipairs(quit_keys) do
        if on then mp.add_forced_key_binding(key, "shot_quit_" .. key, quit_request)
        else mp.remove_key_binding("shot_quit_" .. key) end
    end
end

-- ── exit: nothing half done ───────────────────────────────────────────────────
-- A reject / restore normally lands in on_load a moment after the key press;
-- quitting in between carries it out here (files are closed by now).

mp.register_event("shutdown", function()
    stop_scan()
    local action = pending_action
    pending_action = nil
    if action then
        run_action(action)
        if action.notice then export.dirty, export.xml = true, action.xml end
    end
    -- Anything but Yes puts the disk back: No, or a quit that never showed the
    -- prompt (the default is No, so nothing is overwritten by accident).
    local keep = export.choice == "yes" or encoding
    if not keep and #session.journal > 0 then revert_session() end
end)
