-- The note box: drawn under the state row (mpv's own input line sits at the
-- bottom, under the playback controls), pre-filled with the shot's note. Enter
-- keeps the text, Esc leaves the note as it was. While it's open every key types.
notes.box = nil          -- {r, num, chars = {utf-8 characters}, pos = characters before the cursor}
notes.keys = {}         -- the forced bindings while the box is open

function notes.chars(s)
    local out = {}
    for ch in (s or ""):gmatch("[%z\1-\127\194-\244][\128-\191]*") do out[#out + 1] = ch end
    return out
end

function notes.close(keep)
    local b = notes.box
    if not b then return end
    notes.box = nil
    B.note_rect, B.box_click, B.note_lines, B.note_geo, B.box_move = nil, nil, nil, nil, nil
    drag.hold("note", false)
    notes.report()
    for _, name in ipairs(notes.keys) do mp.remove_key_binding(name) end
    notes.keys = {}
    if keep and b.on_keep then
        b.on_keep(trim(table.concat(b.chars):gsub("[%c]+", " ")))
    elseif keep then
        local text = trim(table.concat(b.chars):gsub("[%c]+", " "))
        if text ~= notes.of(b.r, b.num) then
            b.r.notes[b.num] = text
            b.r.touched[b.num], b.r.cleared[b.num] = true, nil
            notes.touch(b.r, b.num)
        end
    end
    render(true)
end

-- The box shows only while paused. Playback starting again (the controller's play
-- button, say) would leave it open and unseen, still taking every key: Escape
-- would close a box nobody can see instead of quitting. So it closes, text kept.
mp.observe_property("pause", "bool", function(_, paused)
    if paused == false and notes.box then notes.close(true) end
end)

function notes.edit(shot, prefill, on_keep, title)
    local r = current_review()
    if not r or review_busy or export.prompting or not shot or not shot.num or in_preview(r) then return end
    if notes.box then notes.close(true) end
    mp.set_property_bool("pause", true)   -- the row, and so the box, shows while paused
    local chars = notes.chars(prefill or notes.of(r, shot.num))
    -- pos: characters before the cursor.  anchor: where a selection began (nil: none);
    -- the selection is what lies between the anchor and the cursor
    notes.box = {r = r, num = shot.num, chars = chars, pos = #chars, on_keep = on_keep, title = title}
    local b = notes.box
    local function range()   -- the selection, as characters lo+1 .. hi
        if b.anchor and b.anchor ~= b.pos then return math.min(b.anchor, b.pos), math.max(b.anchor, b.pos) end
    end
    local function text_of(lo, hi) return table.concat(b.chars, "", lo + 1, hi) end
    local function cut()   -- take the selection out
        local lo, hi = range()
        b.anchor = nil
        if not lo then return end
        for _ = lo + 1, hi do table.remove(b.chars, lo + 1) end
        b.pos = lo
        return true
    end
    local function clear() b.chars, b.pos, b.anchor = {}, 0, nil end
    local function all() b.anchor, b.pos = #b.chars > 0 and 0 or nil, #b.chars end
    local function insert(s)
        cut()   -- typing over a selection replaces it
        for _, ch in ipairs(notes.chars(s)) do
            if not ch:match("^%c$") then table.insert(b.chars, b.pos + 1, ch); b.pos = b.pos + 1 end
        end
    end
    local function word(dir)   -- the next word edge from the cursor: a word's start going left, its end going right
        local p, n = b.pos, #b.chars
        if dir < 0 then
            while p > 0 and b.chars[p] == " " do p = p - 1 end
            while p > 0 and b.chars[p] ~= " " do p = p - 1 end
        else
            while p < n and b.chars[p + 1] == " " do p = p + 1 end
            while p < n and b.chars[p + 1] ~= " " do p = p + 1 end
        end
        return p
    end
    local function key(name, fn, complex)
        local id = "shot_note_" .. name
        mp.add_forced_key_binding(name, id, function(e)
            if notes.box ~= b then return end
            if complex and e.event == "up" then return end
            fn(e)
            if notes.box == b then render(true); notes.report() end
        end, {repeatable = true, complex = complex})
        notes.keys[#notes.keys + 1] = id
    end
    -- a key that moves the cursor; with Shift it stretches the selection from where
    -- it began. edge: the end of a selection a plain Left (-1) or Right (1) drops to
    local function go(names, to, edge)
        for _, name in ipairs(names) do
            key(name, function()
                local lo, hi = range()
                b.anchor = nil
                if lo and edge then b.pos = edge < 0 and lo or hi else b.pos = to() end
            end)
            key("Shift+" .. name, function() b.anchor = b.anchor or b.pos; b.pos = to() end)
        end
    end
    key("ANY_UNICODE", function(e) insert(e.key_text or "") end, true)
    key("SPACE", function() insert(" ") end)
    key("BS", function()
        if not cut() and b.pos > 0 then table.remove(b.chars, b.pos); b.pos = b.pos - 1 end
    end)
    key("DEL", function()
        if not cut() and b.pos < #b.chars then table.remove(b.chars, b.pos + 1) end
    end)
    go({"LEFT"}, function() return math.max(0, b.pos - 1) end, -1)
    go({"RIGHT"}, function() return math.min(#b.chars, b.pos + 1) end, 1)
    -- by word: Ctrl, and Alt as well (macOS can keep Ctrl+arrows for switching desktops)
    go({"Ctrl+LEFT", "Alt+LEFT"}, function() return word(-1) end)
    go({"Ctrl+RIGHT", "Alt+RIGHT"}, function() return word(1) end)
    go({"UP", "HOME"}, function() return 0 end)
    go({"DOWN", "END"}, function() return #b.chars end)
    key("Ctrl+a", all)
    key("Meta+a", all)
    key("Ctrl+e", function() b.anchor, b.pos = nil, #b.chars end)
    key("Ctrl+u", clear)
    -- copy and cut take the selection, or the whole note when nothing is selected,
    -- so a note moves between shots: copy here, n on the other shot, paste
    for _, k in ipairs({"Ctrl+c", "Meta+c"}) do
        key(k, function()
            local lo, hi = range()
            mp.set_property("clipboard/text", lo and text_of(lo, hi) or table.concat(b.chars))
            osd(lo and "copied" or "note copied", 1)
        end)
    end
    for _, k in ipairs({"Ctrl+x", "Meta+x"}) do
        key(k, function()
            local lo, hi = range()
            mp.set_property("clipboard/text", lo and text_of(lo, hi) or table.concat(b.chars))
            if lo then cut() else clear() end
            osd(lo and "cut" or "note cut", 1)
        end)
    end
    for _, k in ipairs({"Ctrl+v", "Meta+v"}) do
        key(k, function() insert((mp.get_property("clipboard/text") or ""):gsub("[\r\n]+", " ")) end)
    end
    -- the mouse in the box, like any text field: a click puts the cursor there, a
    -- drag selects from there, two clicks select the word, three the whole note.
    -- A click elsewhere still works the state row
    b.clicks = {}
    local function word_at(p)   -- the word (or run of spaces) at a cursor position
        local n = #b.chars
        if n == 0 then return 0, 0 end
        local i = (b.chars[p + 1] and b.chars[p + 1] ~= " ") and p + 1 or math.max(1, p)
        local space = b.chars[i] == " "
        local lo, hi = i, i
        while lo > 1 and (b.chars[lo - 1] == " ") == space do lo = lo - 1 end
        while hi < n and (b.chars[hi + 1] == " ") == space do hi = hi + 1 end
        return lo - 1, hi
    end
    local function click(e)
        local ev = e and e.event or "down"
        if ev == "up" then   -- the end of a drag: nothing dragged over is no selection
            if b.dragging then
                b.dragging = false
                if b.anchor == b.pos then b.anchor = nil end
                render(true)
                notes.report()
            end
            return
        end
        if ev ~= "down" and ev ~= "press" then return end
        local now = mp.get_time()
        local r = B.note_rect
        local p = drag.pointer_on(function(q)
            if r and q.x >= r[1] and q.x <= r[3] and q.y >= r[2] and q.y <= r[4] then return true end
            for _, bt in ipairs(buttons) do
                if bt.enabled and q.x >= bt.x0 and q.x <= bt.x1 and q.y >= bt.y0 and q.y <= bt.y1 then return true end
            end
        end)
        local inside = p and r and p.x >= r[1] and p.x <= r[3] and p.y >= r[2] and p.y <= r[4]
        if not inside then
            b.clicks = {}
            for _, bt in ipairs(buttons) do
                if bt.enabled and p and p.x >= bt.x0 and p.x <= bt.x1 and p.y >= bt.y0 and p.y <= bt.y1 then
                    if review_click then review_click(bt.name) end
                    return
                end
            end
            return
        end
        if #b.clicks > 0 and now - b.clicks[#b.clicks] > 0.5 then b.clicks = {} end
        b.clicks[#b.clicks + 1] = now
        local at = B.note_at(p.x, p.y) or b.pos
        b.dragging = false
