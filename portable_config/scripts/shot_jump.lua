local function read_file(p)
    local f = io.open(p, "rb")
    if not f then return nil end
    local s = f:read("*a")
    f:close()
    return s
end

local function write_file(p, s)
    local f, err = io.open(p, "wb")
    if not f then msg.error("write failed: " .. p .. " (" .. tostring(err) .. ")"); return false end
    f:write(s)
    f:close()
    return true
end

-- Write beside the target, then rename, so a half-written file is never read
local function write_new_file(p, s)
    local tmp = p .. ".tmp"
    if not write_file(tmp, s) then return false end
    if os.rename(tmp, p) then return true end
    os.remove(tmp)
    return false
end

local function pct_decode(s)
    return (s:gsub("%%(%x%x)", function(h) return string.char(tonumber(h, 16)) end))
end

local function pct_encode(s)
    return (s:gsub("[^%w%-%._~/]", function(c) return string.format("%%%02X", c:byte()) end))
end

local function utf8_char(cp)
    if cp < 0x80 then return string.char(cp) end
    if cp < 0x800 then return string.char(0xC0 + math.floor(cp / 0x40), 0x80 + cp % 0x40) end
    if cp < 0x10000 then
        return string.char(0xE0 + math.floor(cp / 0x1000), 0x80 + math.floor(cp / 0x40) % 0x40, 0x80 + cp % 0x40)
    end
    return string.char(0xF0 + math.floor(cp / 0x40000), 0x80 + math.floor(cp / 0x1000) % 0x40,
                       0x80 + math.floor(cp / 0x40) % 0x40, 0x80 + cp % 0x40)
end

local function xml_unescape(s)
    s = s:gsub("&#[xX](%x+);", function(h) return utf8_char(tonumber(h, 16)) end)
    s = s:gsub("&#(%d+);", function(d) return utf8_char(tonumber(d)) end)
    return (s:gsub("&lt;", "<"):gsub("&gt;", ">"):gsub("&quot;", '"'):gsub("&apos;", "'"):gsub("&amp;", "&"))
end

local function xml_escape(s)
    return (s:gsub("&", "&amp;"):gsub("<", "&lt;"):gsub(">", "&gt;"):gsub('"', "&quot;"))
end

local function run(args)
    return utils.subprocess({args = args, cancellable = false, playback_only = false})
end

local function ps_quote(s) return "'" .. s:gsub("'", "''") .. "'" end

local function mkdir_p(dir)
    if exists(dir) then return true end
    local r
    if is_windows then
        r = run({"powershell", "-NoProfile", "-WindowStyle", "Hidden", "-Command",
            "New-Item -ItemType Directory -Force -Path " .. ps_quote(dir) .. " | Out-Null"})
    else
        r = run({"mkdir", "-p", dir})
    end
    return r.status == 0 and exists(dir)
end

-- Remove a folder only if it is empty
local function remove_empty_dir(dir)
    if is_windows then
        run({"powershell", "-NoProfile", "-WindowStyle", "Hidden", "-Command",
             "[System.IO.Directory]::Delete(" .. ps_quote(dir) .. ")"})  -- throws if not empty
    else
        os.remove(dir)  -- rmdir(2) for a folder: fails if not empty
    end
end

-- Move a file; refuses to replace an existing target
local function move_file(src, dst)
    if exists(dst) then return false end
    if os.rename(src, dst) then return true end
    local r
    if is_windows then
        r = run({"powershell", "-NoProfile", "-WindowStyle", "Hidden", "-Command",
            "Move-Item -LiteralPath " .. ps_quote(src) .. " -Destination " .. ps_quote(dst) .. " -ErrorAction Stop"})
    else
        r = run({"mv", "-n", src, dst})
    end
    return r.status == 0 and exists(dst) and not exists(src)
end

-- ── xmeml parsing ─────────────────────────────────────────────────────────────

-- First <name>value</name> in s
local function tag(s, name)
    local v = s and s:match("<" .. name .. "[^>]*>(.-)</" .. name .. ">")
    return v and trim(v)
end

-- Every <name ...>body</name> (or self-closing <name ... />) in s, in order.
-- Assumes the element does not nest inside itself (true for clipitem, file, track).
local function blocks(s, name)
    local out, pos = {}, 1
    while true do
        local a, b, attrs = s:find("<" .. name .. "([%s/][^>]*)>", pos)
        local a2, b2 = s:find("<" .. name .. ">", pos, true)
        if a2 and (not a or a2 < a) then a, b, attrs = a2, b2, "" end
        if not a then break end
        if attrs:match("/%s*$") then
            out[#out + 1] = {attrs = attrs, body = "", s = a, e = b, self = true}
            pos = b + 1
        else
            local c, d = s:find("</" .. name .. ">", b + 1, true)
            if not c then break end
            out[#out + 1] = {attrs = attrs, body = s:sub(b + 1, c - 1), s = a, bs = b + 1, e = d}
            pos = d + 1
        end
    end
    return out
end

local function attr_id(attrs) return attrs and attrs:match('id%s*=%s*"([^"]*)"') end

local function strip(s, name)
    s = s:gsub("<" .. name .. "%s[^>]-/>", "")
    return (s:gsub("<" .. name .. "[%s>].-</" .. name .. ">", ""))
end

local function parse_rate(s)
    local r = s and s:match("<rate>(.-)</rate>")
    local tb = r and tonumber(tag(r, "timebase"))
    if not tb or tb <= 0 then return nil end
    local ntsc = (tag(r, "ntsc") or ""):upper() == "TRUE"
    return ntsc and tb * 1000 / 1001 or tb
end

-- pathurl -> local path. Accepts file:// URLs and paths relative to the XML.
local function url_to_path(url, base_dir)
    url = xml_unescape(trim(url))
    local p
    if url:lower():match("^file:") then
        local rest = url:sub(6)
        if rest:lower():match("^//localhost/") then rest = rest:sub(12)
        elseif rest:match("^///") then rest = rest:sub(3) end
        p = pct_decode(rest)
        if p:match("^/%a:") then p = p:sub(2) end
    else
        p = pct_decode(url)
        if not is_absolute(p) then p = utils.join_path(base_dir, p) end
    end
    return native_seps(p)
end

local function parse_clip(blk, files, seq_fps, base_dir, abs_offset)
    local raw = blk.body
    local fblk = blocks(raw, "file")[1]
    local fid = fblk and attr_id(fblk.attrs)
    local f = fid and files[fid]
    if not f and fblk and not fblk.self then
        f = {pathurl = tag(fblk.body, "pathurl"), name = tag(fblk.body, "name")}
    end
    local top = raw
    for _, t in ipairs({"file", "filter", "link", "comments", "labels", "logginginfo",
                        "colorinfo", "sourcetrack", "sequence"}) do
        top = strip(top, t)
    end
    local comments = raw:match("<comments>(.-)</comments>") or ""
    local c = {
        label = tag(comments, "mastercomment1"),
        label_color = tag(comments, "mastercomment2"),
        id = attr_id(blk.attrs),
        name = xml_unescape(tag(top, "name") or (f and f.name) or "clip"),
        start = tonumber(tag(top, "start")),
        ["end"] = tonumber(tag(top, "end")),
        ["in"] = tonumber(tag(top, "in")),
        out = tonumber(tag(top, "out")),
        enabled = (tag(top, "enabled") or "TRUE"):upper() ~= "FALSE",
        fps = parse_rate(top) or seq_fps,
        file_key = fid or ("inline@" .. (abs_offset + blk.s)),
        pathurl = f and f.pathurl,
        s = abs_offset + blk.s,
    }
    c.path = c.pathurl and c.pathurl ~= "" and url_to_path(c.pathurl, base_dir) or nil
    return c
end

-- Returns {fps, duration (frames), video = {clips}, audio = {clips}} or nil
local function parse_xmeml(text, base_dir)
    local seq_s = text:find("<sequence[%s>]")
    if not text:find("<xmeml") or not seq_s then return nil end
    local media_s = text:find("<media>", seq_s, true)
    if not media_s then return nil end
    local head = strip(text:sub(seq_s, media_s - 1), "timecode")
    local fps = parse_rate(head)
    if not fps then return nil end
    local seq = {fps = fps, duration = tonumber(tag(head, "duration")), video = {}, audio = {}}

    local files = {}
    for _, fb in ipairs(blocks(text, "file")) do
        local id = attr_id(fb.attrs)
        if id and not fb.self and not files[id] then
            files[id] = {pathurl = tag(fb.body, "pathurl"), name = tag(fb.body, "name")}
        end
    end

    -- Tracks after the sequence's <media>; once a sequence-level <audio> opens
    -- between tracks, the rest are audio tracks.
    local media = text:sub(media_s)
    local kind, prev_e = nil, 1
    for _, tb in ipairs(blocks(media, "track")) do
        local between = media:sub(prev_e, tb.s - 1)
        if between:find("<audio>", 1, true) then kind = "audio"
        elseif between:find("<video>", 1, true) then kind = "video" end
        prev_e = tb.e + 1
        local list = kind and seq[kind]
        if list and #list == 0 and tb.body:find("<clipitem", 1, true) then
            local offset = media_s - 1 + tb.bs - 1
            local items = {}
            for _, cb in ipairs(blocks(tb.body, "clipitem")) do
                items[#items + 1] = {pos = cb.s, clip = parse_clip(cb, files, fps, base_dir, offset)}
            end
            for _, xb in ipairs(blocks(tb.body, "transitionitem")) do
                items[#items + 1] = {pos = xb.s, transition_start = tonumber(tag(xb.body, "start"))}
            end
            table.sort(items, function(a, b) return a.pos < b.pos end)
            local last_transition
            for _, it in ipairs(items) do
                if it.clip then
                    if it.clip.start == -1 and last_transition then it.clip.start = last_transition end
                    list[#list + 1] = it.clip
                else
                    last_transition = it.transition_start
                end
            end
        end
    end
    return seq
end

