-- Before the XML is read: a review rebuilds it from the folders and the saved
-- choices, once per session (Save rebuilds it again itself).
review_open = function(xml_path)
    if o.review_xml == "" or name_of(xml_path):lower() ~= o.review_xml:lower() then return end
    if reviews[xml_path] then return end
    local r = {xml = xml_path, root = dir_of(xml_path), marks = {}, touched = {}, cleared = {}, notes = {}, inputs = {}}
    reviews[xml_path] = r
    if o.preview then   -- a look-only launch: the files stay as they are, and nobody is locked out
        r.preview = {view_only = true}
        osd("Preview: view only.\nYou can look and step through versions; nothing can be saved.", 8)
        return
    end
    local other = lock.other(xml_path)
    if other then
        -- someone else is editing: look only, and leave their files alone (no rebuild)
        r.preview = other
        lock.watch()
        osd("Preview: " .. lock.who(other) .. ".\nYou can look and step through versions; nothing can be saved.", 8)
        return
    end
    lock.take(xml_path)
    if o.review_open_cmd == "" then return end
    local args, why = tools.args(r.root, o.review_open_cmd)
    if not args then r.open_note = "review not rebuilt: " .. why; return end
    osd("building the review…", 30)
    local res = tools.run(args)
    local ok, lines = tool_result(res)
    osd("", 0.1)
    if ok then msg.info("review rebuilt: " .. (lines[#lines] or ""))
    elseif tools.never_started(res) then r.open_note = "review not rebuilt: " .. tools.failure(res)
    else r.open_note = "review not rebuilt: " .. (lines[#lines] or tools.failure(res)) end
end

-- After the assembly has loaded: the saved choices, what each slot is really
-- showing (a copy counts as its original), and the keys.
review_loaded = function(asm)
    local r = asm and reviews[asm.xml]
    if r and not asm.review_layout then reviews[asm.xml] = nil; r = nil end
    bind_review_keys(r ~= nil)
    if not r and notes.mode then notes.mode = nil; notes.mode_keys(false) end
    if not r then return end
    if not r.shots then
        for _, shot in ipairs(asm.shots) do
            if shot.rung then r.shots = shot.rung.shots; break end
        end
    end
    if not r.base then r.base = read_selects(r); r.base_imported = notes.read_imported(r) end
    -- seen versions: read once, and the shots' unseen ones on the first load and after a save
    if not r.seen then notes.seen_load(r) end
    -- and whenever the folders have been listed afresh since: new takes light it within a minute
    if not r.unseen or r.rescan or r.unseen_gen ~= session.lists_gen then
        r.rescan = nil
        notes.unseen_scan(r)
        r.unseen_gen = session.lists_gen
    end
    if not notes.seen_timer then notes.seen_timer = mp.add_periodic_timer(0.25, function() notes.seen_tick() end) end
    local cache = session.listing()
    for _, shot in ipairs(asm.shots) do
        if shot.rung and shot.play then
            local rows = shot_versions(shot.rung.shots, shot.rung.nn, cache)
            shot.file = original_of(shot.play, rows) or shot.play
            shot.xml_orig = shot.xml_file and (original_of(shot.xml_file, rows) or shot.xml_file)
            local me
            for _, row in ipairs(rows) do if slash(row.path) == slash(shot.file) then me = row end end
            shot.copies = {}
            for _, row in ipairs(rows) do
                if me and row.letter > me.letter and row.rung and same_file(row, me) then
                    local stage = row.rung:gsub("^%u_", ""):gsub("_", " ")
                    shot.copies[#shot.copies + 1] = stage
                end
            end
        end
    end
    if r.open_note then osd(r.open_note, 6); r.open_note = nil end
    if r.result then mp.add_timeout(0.2, function() if current_review() == r then show_result(r) end end) end
end

-- Is the disk any different from when the session started? Stepping Up / Down
-- and back leaves journal entries but the same XML: nothing to ask about.
local function session_changed()
    for _, e in ipairs(session.journal) do
        if not e.xml_edit then return true end
    end
    for xml, snap in pairs(session.snap) do
        if not snap.review and read_file(xml) ~= snap.text then return true end
    end
    return false
end

