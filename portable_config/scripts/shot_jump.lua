local function open_modal(spec)
    drag.hold("prompt", true)
    mp.set_property_native("user-data/shot_jump/prompt", true)   -- a prompt is up (for other scripts, tests)
    -- the state row's click binding must not sit under the prompt's: two bindings
    -- on the same button and mpv picks either one
    hovered = nil
    set_click_binding(false)
    modal.spec = spec
    modal.sel = spec.default or 1
    export.prompting = true
    mp.set_property_bool("pause", true)
    clear_overlay()
    hide_osc(true)
    local n = #spec.choices
    local function pick(i) return function() close_modal(); spec.done(i) end end
    local function bind(key, fn)
        local name = "shot_modal_" .. key
        mp.add_forced_key_binding(key, name, fn)
        modal_keys[#modal_keys + 1] = name
    end
    local function move(step) return function() modal.sel = (modal.sel - 1 + step) % n + 1; draw_modal() end end
    for i, ch in ipairs(spec.choices) do
        for _, key in ipairs(ch.keys or {}) do bind(key, pick(i)) end
    end
    for _, key in ipairs({"ESC", "q", "Q", "CLOSE_WIN", "Meta+q", "Meta+w", "Ctrl+w"}) do
        bind(key, pick(spec.cancel or n))
    end
    bind("ENTER", function() local i = modal.sel; close_modal(); spec.done(i) end)
    bind("KP_ENTER", function() local i = modal.sel; close_modal(); spec.done(i) end)
    bind("LEFT", move(-1)); bind("RIGHT", move(1)); bind("TAB", move(1)); bind("Shift+TAB", move(-1))
    local function toggle() spec.check.on = not spec.check.on; draw_modal() end
    if spec.check then
        for _, key in ipairs(spec.check.keys or {}) do bind(key, toggle) end
    end
    local function over(m)   -- the button under the pointer
        for i, r in ipairs(modal.rects) do
            if m and m.x >= r[1] and m.x <= r[3] and m.y >= r[2] and m.y <= r[4] then return i end
        end
    end
    local function click()
        local c = modal.check_rect
        local function on_check_(p) return c and p and p.x >= c[1] and p.x <= c[3] and p.y >= c[2] and p.y <= c[4] end
        local m = drag.pointer_on(function(p) return over(p) or on_check_(p) end)
        local i = over(m)
        local on_check = not i and c and m and m.x >= c[1] and m.x <= c[3] and m.y >= c[2] and m.y <= c[4]
        modal.log_click(m, i and spec.choices[i].label or (on_check and "checkbox") or "nothing")
        if i then close_modal(); spec.done(i)
        elseif on_check then toggle() end
    end
    modal_hover = function(m)
        local i = modal.spec == spec and over(m)
        if i and i ~= modal.sel then modal.sel = i; draw_modal() end
    end
    bind("MBTN_LEFT", click)
    bind("MBTN_LEFT_DBL", function() end)
    draw_modal()
    -- the on-screen controller takes the click while it shows; once it has hidden,
    -- bind again so this card's click sits on top (as the shot buttons do)
    mp.add_timeout(0.1, function()
        if modal.spec == spec then mp.add_forced_key_binding("MBTN_LEFT", "shot_modal_MBTN_LEFT", click) end
    end)
end

