local function label_events(events, shot, vx0, vy0, vw, vh, k)
    local label = shot.label
    if not label or label == "" then return end
    local num, rest = label:match("^(%S+)(.*)$")
    num, rest = num or label, rest or ""
    local missing = rest:upper():match("^%s*MISSING PLATE%s*$") ~= nil
    local color = COLORS.white
    if rest:upper():match("^%s*EDIT%s*$") then color = COLORS.gray
    elseif (shot.label_color or ""):lower() == "orange" then color = COLORS.orange end

    local style = string.format("\\bord%.2f\\shad0\\b1\\q2\\3c&H000000&\\3a&H37&\\1a&H00&", L.border * k)
    if missing then
        events[#events + 1] = string.format(
            "{\\an7\\pos(%d,%d)\\p1\\bord0\\shad0\\1c&H1E1ED0&\\1a&H8C&}m 0 0 l %d 0 %d %d 0 %d{\\p0}",
            vx0, vy0, vw, vw, vh, vh)
        events[#events + 1] = string.format("{\\an5\\pos(%.1f,%.1f)%s\\1c&H%s&\\fs%.1f}MISSING PLATE",
            vx0 + vw / 2, vy0 + vh / 2, style, COLORS.white, L.card_fs * k)
        rest, color = "", COLORS.white
    end
    local x = vx0 + vw - L.right * k
    local y = vy0 + vh - (L.baseline - L.descent * L.fs_big) * k
    local line = string.format("{\\an3\\pos(%.1f,%.1f)%s\\1c&H%s&\\fs%.1f\\fscx%d}%s",
        x, y, style, color, L.fs_big * k, L.sx_big, ass_text(num))
    if rest ~= "" then
        line = line .. string.format("{\\fs%.1f\\fscx%d}%s", L.fs_small * k, L.sx_small, ass_text(rest))
    end
    events[#events + 1] = line
end

