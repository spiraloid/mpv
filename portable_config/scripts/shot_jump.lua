-- ── rung layout ──────────────────────────────────────────────────────────────
-- A shots folder whose subfolders are lettered rungs: A_cropped_plates,
-- B_cleaned_plates, ... F_runs, ... I_candidates, ... K_final, with passes in
-- v.NNN folders. A shot's file is NN.<video ext> or NN_v#.<ext> anywhere inside a
-- rung (comp layers, frames, prompts, audio and uncompressed/ masters don't
-- count). Nothing in a rung is moved, copied or renamed by this script: a slot
-- plays the file its XML names (the next one down if that file is gone), Up /
-- Down step through the shot's other versions, and a review saves the choice.

local SKIP_DIRS = {retired = true, uncompressed = true}

local VIDEO_EXT = {}
for _, e in ipairs(mp.get_property_native("video-exts") or
                   {"mp4", "mov", "mkv", "m4v", "avi", "webm", "mxf", "mts"}) do
    VIDEO_EXT[e:lower()] = true
end

local function slash(p) return (p:gsub("\\", "/")) end

local rung_root_memo = {}
local function is_rung_root(shots)
    if rung_root_memo[shots] == nil then
        local n = 0
        for _, d in ipairs(utils.readdir(native_seps(shots), "dirs") or {}) do
            if d:match("^%u_") then n = n + 1 end
        end
        rung_root_memo[shots] = n >= 2
    end
    return rung_root_memo[shots]
end

-- {shots, rung, letter, sub, retired, num, nn, ext} for a shot file inside a rung
local function rung_info(path)
    if not path then return nil end
    local p = slash(path)
    local s0, name, e0
    for s, nm, e in p:gmatch("()/(%u_[^/]+)()") do
        if p:sub(e, e) == "/" then s0, name, e0 = s, nm, e end
    end
    if not s0 then return nil end
    local shots = p:sub(1, s0 - 1)
    if not is_rung_root(shots) then return nil end
    local sub = p:sub(e0 + 1)
    local file = sub:match("([^/]+)$") or sub
    local num = file:match("^(%d+)")
    if not num then return nil end
    return {
        shots = shots, rung = name, letter = name:sub(1, 1),
        sub = sub, retired = sub:match("^retired/") ~= nil,
        num = num, nn = tonumber(num), ext = file:match("%.([^%.]+)$") or "mp4",
    }
end

local function live_path(ri)
    local sub = ri.retired and ri.sub:gsub("^retired/", "", 1) or ri.sub
    return native_seps(ri.shots .. "/" .. ri.rung .. "/" .. sub)
end

local function retired_path(ri)
    local sub = ri.retired and ri.sub or ("retired/" .. ri.sub)
    return native_seps(ri.shots .. "/" .. ri.rung .. "/" .. sub)
end

-- What a rung file shows, the way the burn-in labels read: "07 run 00"
local function rung_label(ri, num_text)
    local stage = ri.rung:gsub("^%u_", ""):gsub("_", " ")
    stage = stage:gsub("([^s])s$", "%1")   -- runs -> run, cleaned plates -> cleaned plate
    local pass = ri.sub:match("v%.(%d+)/")
    pass = pass and string.format(" %02d", tonumber(pass)) or ""
    return (num_text or ri.num) .. " " .. stage .. pass .. (ri.retired and " retired" or "")
end

-- Where a version sits on the tape, oldest to newest: rung letter, then the pass
-- (the v.NNN folder, the number the label shows), then the file's modified time
-- for takes that share a pass (copies keep it), then path as a tie-break. Retired
-- and live copies of a file get the same key.
local function version_key(path, mtime)
    local ri = rung_info(path)
    if not ri then return nil end
    local pass = tonumber(ri.sub:match("v%.(%d+)/")) or -1
    return {ri.letter, pass, mtime or 0, slash(live_path(ri))}
end

local function key_above(a, b)   -- is a later on the tape than b
    for i = 1, #a do
        if a[i] ~= b[i] then return a[i] > b[i] end
    end
    return false
end

-- A rung's shot files (recursive, skipping retired/, uncompressed/ and hidden).
-- all: the shot's whole history instead, with the takes under retired/ and the
-- drivers (NN_driver.<ext>) too; only Up / Down looks at those.
local function rung_files(dir, cache, all)
    local ckey = all and (dir .. "|all") or dir
    if cache[ckey] then return cache[ckey] end
    local out = {}
    local function walk(d, depth)
        if depth > 6 then return end
        for _, f in ipairs(utils.readdir(d, "files") or {}) do
            local num, rest, ext = f:match("^(%d+)(.-)%.([^%.]+)$")
            if num and (rest == "" or rest:match("^_v%d+$") or (all and rest == "_driver"))
               and VIDEO_EXT[ext:lower()] then
                local p = utils.join_path(d, f)
                local info = utils.file_info(p)
                if info and info.is_file and (info.size or 1) > 0 then   -- empty stubs don't count
                    local vk = version_key(p, info.mtime)
                    if vk then
                        out[#out + 1] = {path = p, nn = tonumber(num), mtime = info.mtime or 0, vk = vk,
                                         size = info.size or 0}
                    end
                end
            end
        end
        for _, sd in ipairs(utils.readdir(d, "dirs") or {}) do
            local skip = SKIP_DIRS[sd:lower()] and not (all and sd:lower() == "retired")
            if not skip and sd:sub(1, 1) ~= "." then walk(utils.join_path(d, sd), depth + 1) end
        end
    end
    walk(dir, 0)
    msg.verbose("listed " .. ckey .. ": " .. #out .. " files")
    cache[ckey] = out
    return out
end

-- Which version of the shot this is within its rung, for the small line over the
-- label: "11-21 18:50 · 2 of 3" (file date, place oldest first). Counts live and retired versions together, oldest
-- first.
-- nil when the rung has only one version of the shot.
local function version_detail(ri, play_path, cache)
    local rung_dir = native_seps(ri.shots .. "/" .. ri.rung)
    local rows = {}
    for _, f in ipairs(rung_files(rung_dir, cache)) do
        if f.nn == ri.nn then rows[#rows + 1] = {key = f.vk[#f.vk], mtime = f.mtime, vk = f.vk} end
    end
    for _, f in ipairs(rung_files(utils.join_path(rung_dir, "retired"), cache)) do
        if f.nn == ri.nn then rows[#rows + 1] = {key = f.vk[#f.vk], mtime = f.mtime, vk = f.vk} end
    end
    if #rows < 2 then return nil end
    table.sort(rows, function(a, b) return key_above(b.vk, a.vk) end)
    local here, idx = slash(play_path), nil
    for i, r in ipairs(rows) do if r.key == here then idx = i end end
    if not idx then return nil end
    -- when: the file's date
    local when = os.date("%m-%d %H:%M", rows[idx].mtime)
    return string.format("%s · %d of %d", when, idx, #rows)
end

-- The newest live file for ri's shot in ri's rung, else the next rung down, to A
local function walk_down(ri, cache)
    local shots = native_seps(ri.shots)
    local rungs = {}
    for _, d in ipairs(utils.readdir(shots, "dirs") or {}) do
        if d:match("^%u_") and d:sub(1, 1) <= ri.letter then rungs[#rungs + 1] = d end
    end
    table.sort(rungs, function(a, b) return a > b end)
    for _, r in ipairs(rungs) do
        local best
        for _, f in ipairs(rung_files(utils.join_path(shots, r), cache)) do
            if f.nn == ri.nn and (not best or key_above(f.vk, best.vk)) then best = f end
        end
        if best then return best.path end
    end
    return nil
end

-- What a slot plays and why: "xml" (the file the XML names), "walked" (a fallback
-- after rejects), "rejected" (nothing left), "missing". The folders are the
-- truth, so every copy of the same edit agrees.
local function resolve_source(path, enabled, cache)
    if not path then return nil, "missing" end
    local ri = rung_info(path)
    if ri then
        -- a retired take picked with Up / Down: the XML plays it where it lies
        if ri.retired and enabled and exists(path) then return path, "xml" end
        local live = live_path(ri)
        if exists(live) then return live, "xml" end
        local alt = walk_down(ri, cache)
        if alt then return alt, "walked" end
        if exists(retired_path(ri)) then return retired_path(ri), "rejected" end
        return nil, "missing"
    end
    if exists(path) then return path, enabled and "xml" or "rejected" end
    return nil, "missing"
end

-- The latest state of shot nn: the newest live file in the highest rung that has one
local function top_version(shots, nn, cache)
    local best
    local sdir = native_seps(shots)
    for _, d in ipairs(utils.readdir(sdir, "dirs") or {}) do
        if d:match("^%u_") then
            for _, f in ipairs(rung_files(utils.join_path(sdir, d), cache)) do
                if f.nn == nn and (not best or key_above(f.vk, best.vk)) then best = f end
            end
        end
    end
    return best and best.path or nil
end

local function build_assembly(xml_path, seq)
    local segs, shots, blank = {}, {}, {}
    local t, missing, retired = 0, 0, 0
    local review_layout = false
    local cache = session.listing()
    local last_seg

    -- Resolve every clip first; a missing one still keeps its slot, played from
    -- any clip that exists (the whole frame is painted over, the sound is muted
    -- or replaced by the soundtrack), so nothing after it shifts.
    local filler
    local mine = picks[xml_path] or {}
    for _, c in ipairs(seq.video) do
        c.xml_path = c.path
        -- an Up / Down choice plays in place of the file the XML names
        local pri = c.path and rung_info(c.path)
        local pick = pri and mine[pri.num]
        if pick and exists(pick) then
            c.chosen = slash(pick) ~= slash(c.path)
            c.path, c.enabled = pick, true
        end
        c.resolved, c.how = resolve_source(c.path, c.enabled, cache)
        filler = filler or c.resolved
    end

    for i, c in ipairs(seq.video) do
        local len_f = (c.out and c["in"]) and (c.out - c["in"]) or
                      ((c["end"] and c.start and c.start >= 0) and (c["end"] - c.start) or 0)
        local len = len_f / c.fps
        local src = c.resolved or filler
        if len > 0 and src then
            local is_missing = c.how == "missing"
            local rejected = c.how == "rejected"
            if c.resolved then c.path = c.resolved end
            -- Start 0.1ms early: at an exact start, float rounding in mpv's timeline
            -- drops the segment's first frame (measured on a 23.976 assembly).
            local start = is_missing and 0 or ((c["in"] or 0) / c.fps - SEGMENT_LEAD)
            segs[#segs + 1] = q(src) .. ",start=" .. num(start) ..
                              ",length=" .. num(len) .. ",title=" .. q(c.name)
            last_seg = {src = src, start = start, len = len, fps = c.fps}
            local refs = 0
            for _, other in ipairs(seq.video) do if other.file_key == c.file_key then refs = refs + 1 end end
            local label = c.label and xml_unescape(c.label)
            local num_text = label and label:match("^(%d%S*)")
            local ri = rung_info(c.resolved or c.xml_path)
            local label_color = c.label_color
            if (c.how == "walked" or c.chosen) and ri then
                label, label_color = rung_label(ri, num_text), nil   -- say what is really playing
            end
            shots[#shots + 1] = {t = t, len = len, idx = i, name = c.name, retired = rejected,
                                 missing = is_missing, play = c.resolved,
                                 label = label, label_color = label_color, num_text = num_text,
                                 detail = ri and not rejected and not is_missing and not ri.retired
                                          and version_detail(ri, c.resolved, cache) or nil,
                                 refs = refs, rung = ri, num = ri and ri.num or nil, xml_file = c.xml_path}
            if ri then review_layout = true end
            if rejected then retired = retired + 1 end
            if is_missing then
                missing = missing + 1
                msg.warn("missing source for " .. c.name .. ": " .. tostring(c.path))
            end
            if rejected or is_missing then
                blank[#blank + 1] = string.format("between(t,%.4f,%.4f)",
                    t - 0.25 / seq.fps, t + len - 0.5 / seq.fps)
            end
            t = t + len
        elseif len > 0 then
            missing = missing + 1
            msg.warn("missing source for " .. c.name .. ": " .. tostring(c.path))
        end
    end
    if #segs == 0 then return nil end
    if encoding and last_seg then
        -- mpv's encoder drops a stream's final frame: give it a one-frame spare
        local f = 1 / last_seg.fps
        segs[#segs + 1] = q(last_seg.src) .. ",start=" .. num(last_seg.start + last_seg.len - f) ..
                          ",length=" .. num(f) .. ",title=" .. q("end")
    end

    local soundtrack = false
    local asegs = {}
    -- the render takes its sound from the clip named by export_audio_clip (say,
    -- the approved edit's own audio, kept disabled so an editor doesn't hear it
    -- under the voice), and plays the first audio track otherwise
    local audio, export_sound = seq.audio, nil
    if o.export_audio_clip ~= "" then
        for _, c in ipairs(seq.audio_more or {}) do
            if c.id == o.export_audio_clip and c.path and exists(c.path) then export_sound = c end
        end
    end
    if encoding and export_sound then
        audio = {export_sound}
        export_sound.enabled = true
        msg.info("render sound: " .. export_sound.path)
    end
    local function seg(c, force)
        local len = (c.out and c["in"]) and (c.out - c["in"]) / c.fps or 0
        if len > 0 and c.path and exists(c.path) and (c.enabled or force) then
            return q(c.path) .. ",start=" .. num((c["in"] or 0) / c.fps) .. ",length=" .. num(len)
        end
    end
    for _, c in ipairs(audio) do asegs[#asegs + 1] = seg(c) end
    local edl = "edl://" .. table.concat(segs, ";")
    if #asegs > 0 then
        soundtrack = true
        edl = edl .. ";!new_stream;!track_meta,title=" .. q(SOUNDTRACK_TITLE) .. ";" .. table.concat(asegs, ";")
    end
    -- playing: the render's sound rides along as a second stream, so A can switch to
    -- it, from a copy on this computer (nil until that copy is made)
    local copy = not encoding and export_sound and export.sound_file and export.sound_file(export_sound)
    local esg = copy and seg(setmetatable({path = copy}, {__index = export_sound}), true)
    if esg then
        soundtrack = true
        edl = edl .. ";!new_stream;!track_meta,title=" .. q(export.sound_title) .. ";" .. esg
    end
    return {
        xml = xml_path, seq = seq, edl = edl, shots = shots, blank = blank,
        soundtrack = soundtrack, missing = missing, retired = retired, fps = seq.fps,
        export_sound = export_sound ~= nil,
        export_name = export_sound and name_of(export_sound.path) or nil,
        source_name = seq.audio[1] and seq.audio[1].path and name_of(seq.audio[1].path) or nil,
        review_layout = review_layout,
    }
end

-- Folder for a retired source: retired/<path relative to the XML folder>,
-- so same-named clips from different folders never collide.
local function retired_dest(xml_dir, src)
    local norm = function(p) return (p:gsub("\\", "/")) end
    local d, s = norm(xml_dir) .. "/", norm(src)
    local rel
    if (is_windows and s:lower():sub(1, #d) == d:lower()) or s:sub(1, #d) == d then
        rel = s:sub(#d + 1)
    else
        rel = name_of(src)
    end
    if rel:sub(1, #o.retired_dir + 1) == o.retired_dir .. "/" then rel = rel:sub(#o.retired_dir + 2) end
    local dest = native_seps(norm(xml_dir) .. "/" .. o.retired_dir .. "/" .. rel)
    if not exists(dest) then return dest end
    local stem, ext = dest:match("^(.*)(%.[^%./\\]+)$")
    stem, ext = stem or dest, ext or ""
    for n = 1, 999 do
        local alt = stem .. "_" .. n .. ext
        if not exists(alt) then return alt end
    end
    return nil
end

local function path_to_pathurl(path, xml_dir, was_url)
    local p = path:gsub("\\", "/")
    if was_url then
        if p:match("^%a:") then p = "/" .. p end
        return "file://localhost" .. pct_encode(p)
    end
    -- relative to the XML's folder (../shots/... from a subfolder); absolute if
    -- nothing is shared (another drive)
    local a, b = {}, {}
    for s in xml_dir:gsub("\\", "/"):gmatch("[^/]+") do a[#a + 1] = s end
    for s in p:gmatch("[^/]+") do b[#b + 1] = s end
    local function same(x, y) return x == y or (is_windows and x:lower() == y:lower()) end
    local n = 0
    while n < #a and n < #b - 1 and same(a[n + 1], b[n + 1]) do n = n + 1 end
    if n == 0 then return pct_encode(p) end
    local parts = {}
    for _ = n + 1, #a do parts[#parts + 1] = ".." end
    for i = n + 1, #b do parts[#parts + 1] = b[i] end
    return pct_encode(table.concat(parts, "/"))
end

-- Mark every clipitem using file_key as disabled and point the file at new_url
-- enable = false: reject (insert/set <enabled>FALSE</enabled>, point at retired/)
-- enable = true:  undo a reject (take that line out again, point back)
local function rewrite_xml(text, file_key, new_url, enable, label)
    local nl = text:find("\r\n", 1, true) and "\r\n" or "\n"
    local edits = {}
    local function edit(s, e, rep) edits[#edits + 1] = {s = s, e = e, rep = rep} end

    for _, cb in ipairs(blocks(text, "clipitem")) do
        local fb = blocks(cb.body, "file")[1]
        local key = fb and attr_id(fb.attrs) or ("inline@" .. cb.s)
        if key == file_key then
            local body = cb.body
            local file_s = body:find("<file[%s/>]") or (#body + 1)
            local prefix = body:sub(1, file_s - 1)
            local a, b = prefix:find("<enabled>.-</enabled>")
            if enable then
                -- the line a reject inserted right after </name> goes; any other is set TRUE
                local s1, e1 = prefix:find("</name>\r?\n[ \t]*<enabled>FALSE</enabled>")
                if s1 then
                    edit(cb.bs + s1 + 6, cb.bs + e1 - 1, "")
                elseif a then
                    edit(cb.bs + a - 1, cb.bs + b - 1, "<enabled>TRUE</enabled>")
                end
            elseif a then
                edit(cb.bs + a - 1, cb.bs + b - 1, "<enabled>FALSE</enabled>")
            else
                local _, ne = prefix:find("</name>", 1, true)
                local indent = prefix:match("\n([ \t]*)<name") or ""
                local at = ne and (cb.bs + ne) or cb.bs
                edit(at, at - 1, nl .. indent .. "<enabled>FALSE</enabled>")
            end
            if fb and not fb.self then
                local pa, pb = fb.body:find("<pathurl>.-</pathurl>")
                if pa then
                    local base = cb.bs + fb.bs - 1
                    edit(base + pa - 1, base + pb - 1, "<pathurl>" .. xml_escape(new_url) .. "</pathurl>")
                end
            end
            if label then
                local la, lb = body:find("<mastercomment1>.-</mastercomment1>")
                if la then
                    edit(cb.bs + la - 1, cb.bs + lb - 1, "<mastercomment1>" .. xml_escape(label) .. "</mastercomment1>")
                end
            end
        end
    end
    -- the file definition may sit in a clipitem that is not ours (shared id)
    if not file_key:match("^inline@") then
        for _, fb in ipairs(blocks(text, "file")) do
            if attr_id(fb.attrs) == file_key and not fb.self then
                local pa, pb = fb.body:find("<pathurl>.-</pathurl>")
                if pa then
                    local s = fb.bs + pa - 1
                    local dup = false
                    for _, ed in ipairs(edits) do if ed.s == s then dup = true end end
                    if not dup then edit(s, fb.bs + pb - 1, "<pathurl>" .. xml_escape(new_url) .. "</pathurl>") end
                end
                break
            end
        end
    end
    table.sort(edits, function(x, y) return x.s > y.s end)
    for _, ed in ipairs(edits) do
        text = text:sub(1, ed.s - 1) .. ed.rep .. text:sub(ed.e + 1)
    end
    return text
end

-- Runs inside on_load, after mpv has closed the previous timeline, so the
-- source is no longer held open (Windows refuses to move an open file).
local function do_retire(p)
    local xml_dir = dir_of(p.xml)
    local dest = retired_dest(xml_dir, p.path)
    if not dest or not mkdir_p(dir_of(dest)) then
        osd("reject failed: could not create the retired folder", 3); return
    end
    if not move_file(p.path, dest) then
        osd("reject failed: could not move " .. name_of(p.path), 3); return
    end
    journal_move(p.path, dest)
    local text = read_file(p.xml)
    if not text then osd("moved, but could not read the XML", 3); return end
    local bak = p.xml .. ".bak"
    if not exists(bak) then write_file(bak, text) end
    local was_url = (p.pathurl or ""):lower():match("^file:") ~= nil
    local new_text = rewrite_xml(text, p.file_key, path_to_pathurl(dest, xml_dir, was_url), false)
    if not write_file(p.xml, new_text) then
        osd("moved, but could not update the XML", 3); return
    end
    msg.info("retired " .. p.path .. " -> " .. dest)
    p.notice = "rejected: " .. p.name
end

-- Undo a reject as if it never happened: the clip goes back where it was (its
-- run folder recreated), the XML loses the <enabled>FALSE</enabled> and gets
-- its pathurl back, and the .bak goes if the XML now matches it again.
local function do_restore(p)
    local xml_dir = dir_of(p.xml)
    if p.orig ~= p.path then
        if exists(p.orig) or not mkdir_p(dir_of(p.orig)) or not move_file(p.path, p.orig) then
            osd("restore failed: could not move " .. name_of(p.path) .. " back", 3); return
        end
        journal_move(p.path, p.orig)
        -- take out the folders under retired/ (and retired/ itself) that are now empty
        local dir = dir_of(p.path)
        while dir:gsub("\\", "/"):find("/" .. o.retired_dir .. "/", 1, true) or
              name_of(dir) == o.retired_dir do
            remove_empty_dir(dir)
            if exists(dir) or name_of(dir) == o.retired_dir then break end
            dir = dir_of(dir)
        end
    end
    local text = read_file(p.xml)
    if not text then osd("moved back, but could not read the XML", 3); return end
    local was_url = (p.pathurl or ""):lower():match("^file:") ~= nil
    local new_text = rewrite_xml(text, p.file_key, path_to_pathurl(p.orig, xml_dir, was_url), true)
    if not write_file(p.xml, new_text) then
        osd("moved back, but could not update the XML", 3); return
    end
    local bak = p.xml .. ".bak"
    if read_file(bak) == new_text then os.remove(bak) end
    msg.info("restored " .. p.path .. " -> " .. p.orig)
    p.notice = "restored: " .. p.name
end

-- ── validation: does the XML match the folders? ───────────────────────────────

local function short_path(path, xml_dir)
    local p, d = slash(path), slash(xml_dir) .. "/"
    if p:sub(1, #d) == d then return p:sub(#d + 1) end
    return p
end

local function version_text(path)
    local ri = rung_info(path)
    local info = utils.file_info(path)
    local when = info and os.date(" (%m-%d %H:%M)", info.mtime) or ""
    return (ri and rung_label(ri):gsub("^%S+ ", "") or name_of(path)) .. when
end

-- Returns {fixable = {lines}, notes = {lines}}. Fixable means Regenerate resolves it.
local function validate(asm, seq, xml_path)
    local fix, notes = {}, {}
    local targets = {}   -- file_key -> the file Regenerate points that slot at
    local xml_dir = dir_of(xml_path)
    local cache = {}
    -- When the XML was last saved: a newer version that already existed then was
    -- passed over on purpose (an Up / Down pick); only one made since is news
    local xinfo = utils.file_info(xml_path)
    local saved_at = xinfo and xinfo.mtime or 0
    local function who(c)
        local l = c.label and xml_unescape(c.label)
        return (l and l:match("^(%d%S*)")) or c.name or "clip"
    end
    -- structure
    local prev_end, prev
    for _, c in ipairs(seq.video) do
        if c.start and c.start >= 0 and c["end"] then
            if prev_end and c.start ~= prev_end then
                notes[#notes + 1] = string.format("%s: %s of %d frames before it", who(c),
                    c.start > prev_end and "gap" or "overlap", math.abs(c.start - prev_end))
            end
            if c.out and c["in"] and (c.out - c["in"]) ~= (c["end"] - c.start) then
                notes[#notes + 1] = string.format("%s: slot is %d frames but its in/out covers %d",
                    who(c), c["end"] - c.start, c.out - c["in"])
            end
            prev_end, prev = c["end"], c
        end
    end
    if seq.duration and prev_end and seq.duration ~= prev_end then
        notes[#notes + 1] = string.format("sequence says %d frames, clips end at %d", seq.duration, prev_end)
    end
    -- each slot against the folders
    for _, c in ipairs(seq.video) do
        local named = c.xml_path
        local ri = rung_info(c.resolved or named)
        if c.how == "missing" then
            local nri = named and rung_info(named)
            local alt = nri and top_version(nri.shots, nri.nn, cache)
            local line = string.format("%s: no file at %s", who(c), short_path(named or "?", xml_dir))
            if alt then fix[#fix + 1] = line .. "; latest is " .. version_text(alt); targets[c.file_key] = alt
            else notes[#notes + 1] = line .. " (no other version of the shot)" end
        elseif c.how == "walked" then
            fix[#fix + 1] = string.format("%s: names %s, which is retired or gone; playing %s",
                who(c), short_path(named, xml_dir), version_text(c.resolved))
            targets[c.file_key] = c.resolved   -- keep what's on screen
        elseif c.how == "rejected" and c.enabled then
            fix[#fix + 1] = string.format("%s: every version is retired, but the XML still plays it", who(c))
        end
        if ri and (c.how == "xml" or c.how == "walked") then
            local top = top_version(ri.shots, ri.nn, cache)
            if top and slash(top) ~= slash(c.resolved) then
                local tinfo = utils.file_info(top)
                local line = string.format("%s: plays %s; latest is %s", who(c), version_text(c.resolved), version_text(top))
                if tinfo and (tinfo.mtime or 0) > saved_at then fix[#fix + 1] = line; targets[c.file_key] = top
                else notes[#notes + 1] = line .. " (picked over it when the XML was saved)" end
            end
        end
    end
    -- run folders named on different clocks ("11-22__1242" vs the file's time)
    local shots_dirs = {}
    for _, c in ipairs(seq.video) do
        local ri = rung_info(c.resolved or c.xml_path)
        if ri then shots_dirs[ri.shots] = true end
    end
    for shots in pairs(shots_dirs) do
        local clocks = {}
        local sdir = native_seps(shots)
        for _, d in ipairs(utils.readdir(sdir, "dirs") or {}) do
            if d:match("^%u_") then
                for _, f in ipairs(rung_files(utils.join_path(sdir, d), cache)) do
                    local mo, da, hh, mi = slash(f.path):match("/(%d%d)%-(%d%d)__(%d%d)(%d%d)/[^/]+$")
                    if mo then
                        local y = tonumber(os.date("%Y", f.mtime))
                        local named_t = os.time({year = y, month = tonumber(mo), day = tonumber(da),
                                                 hour = tonumber(hh), min = tonumber(mi)})
                        local off = math.floor((named_t - f.mtime) / 3600 + 0.5)
                        local bucket = math.floor((off + 1) / 3) * 3     -- runs take minutes: group within ~3h
                        clocks[bucket] = (clocks[bucket] or 0) + 1
                    end
                end
            end
        end
        local list = {}
        for off, n in pairs(clocks) do list[#list + 1] = {off, n} end
        if #list > 1 then
            table.sort(list, function(a, b) return a[2] > b[2] end)
            local parts = {}
            for _, e in ipairs(list) do parts[#parts + 1] = string.format("%+dh ×%d", e[1], e[2]) end
            notes[#notes + 1] = "run folders are named on different clocks (" .. table.concat(parts, ", ") ..
                "), so their names don't sort by time; versions are ordered by pass, then file date"
        end
    end
    for _, l in ipairs(fix) do msg.warn("validation: " .. l) end
    for _, l in ipairs(notes) do msg.info("validation note: " .. l) end
    return {fixable = fix, notes = notes, targets = targets}
end

local function run_action(action)
    if action.kind == "reject" then do_retire(action)
    elseif action.kind == "restore" then do_restore(action) end
    if action.kind ~= "choose" then session.relist() end   -- files moved
    -- "choose" (Up / Down, a review reload): nothing happens on disk
end

mp.add_hook("on_load", 50, function()
    -- a second mpv handing its file to the one already running (single_instance.lua)
    if mp.get_property_native("user-data/single_instance/leaving") then return end
    local url = mp.get_property("stream-open-filename", "")
    if not is_xml(url) or url:find("://", 1, true) then return end
    local xml_path = absolute(url)
    if review_open and not encoding then review_open(xml_path) end   -- a review rebuilds its XML first
    local text = read_file(xml_path)
    if not text or not text:find("<xmeml", 1, true) then return end

    local first_load = not session.snap[xml_path]
    if first_load then
        -- a review's XML is rebuilt by the project's scripts, never by this one:
        -- nothing to put back
        session.snap[xml_path] = reviews[xml_path] and {review = true}
                                 or {text = text, bak = exists(xml_path .. ".bak")}
    end
    local action = pending_action
    pending_action = nil
    if action and action.xml == xml_path then
        run_action(action)
        if action.notice and action.kind ~= "choose" then export.dirty, export.xml = true, xml_path end
        text = read_file(xml_path) or text
        mp.set_property("file-local-options/start", tostring(action.pos))
    end

    local seq = parse_xmeml(text, dir_of(xml_path))
    local asm = seq and build_assembly(xml_path, seq)
    if not asm then
        msg.warn("no playable clips in " .. xml_path)
        osd("XML has no playable clips", 3)
        return
    end
    asm.url = url
    asm.generated = text:find(GENERATED_MARK, 1, true) ~= nil
    asm.notice = action and action.notice
    if first_load and not encoding and not asm.generated then validate(asm, seq, xml_path) end   -- to the log
    mp.set_property("stream-open-filename", asm.edl)
    local chain = {}
    if #asm.blank > 0 then
        -- a slot with nothing left (rejected all the way down) or missing plays as a
        -- dark gray "virtual clip"; render() adds the card
        local expr = table.concat(asm.blank, "+")
        chain[#chain + 1] = "drawbox=c=0x" .. REJECTED_GRAY .. ":t=fill:enable='" .. expr .. "'"
        if not asm.soundtrack then
            mp.set_property("file-local-options/af", "lavfi=[volume=volume=0:enable='" .. expr .. "']")
        end
    end
    if encoding then
        -- one picture for the whole render: the encoder stops at the first clip whose
        -- size or pixel format differs from the one before (a 10-bit take among 8-bit)
        local same = "format=yuv420p"
        if seq.w and seq.h and seq.w > 0 and seq.h > 0 then
            same = string.format("scale=%d:%d:force_original_aspect_ratio=decrease,pad=%d:%d:(ow-iw)/2:(oh-ih)/2,setsar=1,",
                                 seq.w, seq.h, seq.w, seq.h) .. same
        end
        table.insert(chain, 1, same)
        -- constant frame rate: a source shorter than its slot holds its last frame
        local f = asm.fps
        local rate = math.abs(f - round(f)) > 0.001 and string.format("%d/1001", round(f * 1001)) or tostring(round(f))
        chain[#chain + 1] = "fps=" .. rate .. ":eof_action=pass"
    end
    if #chain > 0 then mp.set_property("file-local-options/vf", "lavfi=[" .. table.concat(chain, ",") .. "]") end
    pending_assembly = asm
end)

