end

-- Shift+D in select mode: the pinned driver as footage (the take itself) or as
-- depth (a depth video made from it); footage when "kind" is left out
-- The driver's kind: "mask" (the take's matte as the red key figure over the
-- plate) or "depth" (a depth video made from the take). Shift+D / Tab flip it
function notes.driver_kind()
    local m = notes.mode
    if not m then return end
    local ins = notes.inputs_of(m.r, m.num)
    if not ins or not ins.driver then osd("no driver pinned yet: d pins the take on screen", 2); return end
    notes.pin(ins.driver.kind == "depth" and "mask" or "depth", true)
end

-- Inputs the model can't take together: turning one on turns the others off.
-- The project's defaults file can say ({"input_conflicts": {"depth": ["start"]}},
-- either way round); without it a depth driver and a start frame exclude each
-- other. The mask and depth drivers always do: there's one driver.
function notes.conflicts_of(r, kind)
    notes.recirc_default(r)   -- reads the defaults file (and its conflicts) if it's due
    local table_ = notes.conflicts or {depth = {"start"}}
    local out = {}
    for a, list in pairs(table_) do
        if type(list) == "table" then
            for _, b in ipairs(list) do
                if a == kind then out[b] = true elseif b == kind then out[a] = true end
            end
        end
    end
    return out
end

-- In select mode, from the keys or the bar's boxes: the take on screen (any
-- shot) as the select's mask / depth driver, the frame on screen as its start /
-- end frame. On a box that's set for the take (or frame) on screen it unpins;
-- set for another one, it moves to this one. kind_only: switch the pinned
-- driver's kind, whichever take it is
function notes.pin(kind, kind_only)
    if kind == "driver" then kind = "mask" end
    local m, r, shot, asm = notes.mode, current_review(), current_shot(), state.assembly
    if not m or r ~= m.r or not asm then return end
    local ins = {}
    for k, v in pairs(notes.inputs_of(r, m.num) or {}) do ins[k] = v end
    local function set(t)
        r.inputs[m.num] = next(t) and t or false
        notes.touch(r, m.num)
        r.touched[m.num], r.cleared[m.num] = true, nil
        -- the driver went off (unticked, or turned off by a frame): its note box goes too
        if not t.driver and notes.box and notes.box.on_tab then notes.close(false) end
        render(true)
    end
    local function clear_conflicts(t, k)   -- k is turning on: what it can't go with goes off
        local off = {}
        for c in pairs(notes.conflicts_of(r, k)) do
            if (c == "start" or c == "end") and t[c] then t[c] = nil; off[#off + 1] = c .. " frame" end
            if (c == "mask" or c == "depth") and t.driver and (t.driver.kind or "footage") == c then
                t.driver = nil; off[#off + 1] = c .. " driver"
            end
        end
        return #off > 0 and ("   (off: " .. table.concat(off, ", ") .. ")") or ""
    end
    local function as(d, k)   -- a copy of the driver as kind k
        local c = {}
        for kk, vv in pairs(d) do c[kk] = vv end
        c.kind = k
        return c
    end
    if kind_only then
        if ins.driver then
            ins.driver = as(ins.driver, kind)
            local off = clear_conflicts(ins, kind)
            set(ins); osd("driver for " .. m.num .. ": " .. kind .. off, 2)
        end
        return
    end
    if not shot or not shot.rung or shot.missing or shot.retired then osd("nothing to pin here", 1.5); return end
    local file = rel_file(r, shot.file or shot.play)
    if not file then osd("this take is outside the review's folder", 2); return end
    local what = rung_label(rung_info(shot.file or shot.play), shot.num_text)
    if kind == "mask" or kind == "depth" then
        local cur = ins.driver
        if cur and cur.file == file then
            if (cur.kind or "footage") == kind then ins.driver = nil; set(ins); osd(kind .. " driver unpinned", 1.5); return end
            ins.driver = as(cur, kind)
            local off = clear_conflicts(ins, kind)
            set(ins); osd(kind .. " driver for " .. m.num .. ": " .. what .. off, 2); return
        end
        ins.driver = {file = file, kind = kind, note = ""}
        local off = clear_conflicts(ins, kind)
        set(ins)
        local target = notes.mode_target(m)
        local fps = asm.fps or 24
        local want, have = target and math.floor(target.len * fps + 0.5), math.floor(shot.len * fps + 0.5)
        local warn = (target and target ~= shot and want ~= have)
            and string.format("   (driver is %d frames, %s is %d: the run needs them equal)", have, m.num, want) or ""
        osd(kind .. " driver for " .. m.num .. ": " .. what .. warn .. off, 4)
        local function title() return "Driver Prompt" end   -- the box on the bar says which kind
        notes.edit(shot, "", function(text)
            local now = notes.inputs_of(r, m.num)
            if now and now.driver and now.driver.file == file then
                local t = {}
                for k, v in pairs(now) do t[k] = v end
                t.driver = {file = file, note = text, kind = now.driver.kind}
                set(t)
            end
        end, title())
        -- the box takes every key, Shift+D included: Tab flips the kind from inside it
        if notes.box then
            notes.box.on_tab = function(bx) notes.driver_kind(); bx.title = title() end
        end
        return
    end
    local clip = asm.seq.video[shot.idx]
    local fps = asm.fps or 24
    local pos = mp.get_property_number("time-pos") or shot.t
    local n = math.max(1, math.floor(shot.len * fps + 0.5))
    local off = math.min(n - 1, math.max(0, math.floor((pos - shot.t) * fps + 0.5)))
    local frame = (clip and clip["in"] or 0) + off
    local cur = ins[kind]
    if cur and cur.file == file and cur.frame == frame then
        ins[kind] = nil; set(ins); osd(kind .. " frame unpinned", 1.5); return
    end
    local dir = mp.command_native({"expand-path", "~~/cache"})
    if not mkdir_p(dir) then osd("could not make mpv's cache folder", 3); return end
    local grab = utils.join_path(dir, string.format("pin-%s-%s-%d.png", m.num, kind, os.time()))
    mp.commandv("screenshot-to-file", grab, "video")
    if not exists(grab) then osd("could not grab the frame", 3); return end
    ins[kind] = {file = file, frame = frame, grab = grab}
    local off = clear_conflicts(ins, kind)
    set(ins)
    osd(string.format("%s frame for %s: %s, frame %d%s", kind, m.num, what, frame, off), 3)
end

-- saving -----------------------------------------------------------------------

-- What Save would write for the shot: {file, mark, note}, or nil for no entry
local function review_entry(r, shot)
    if r.cleared[shot.num] then return nil end
    local file = notes.select_of(r, shot)
    if not file then return nil end
    local mark, comp = mark_of(r, shot), notes.comp_of(r, shot)
    local b = r.base[shot.num]
    -- never chosen and not marked: only a version other than the XML's own is a choice
    local note = notes.of(r, shot.num)
    local inputs = notes.inputs_of(r, shot.num)
    if not b and not mark and not comp and note == "" and not inputs and file == slash(shot.xml_orig or "") then return nil end
    -- who: only while there is a state, the comp switch, a note or inputs to answer for
    local by = (mark or comp or note ~= "" or inputs) and notes.by_of(r, shot.num) or nil
    return {file = file, mark = mark, comp = comp, note = note, by = by, inputs = inputs}
end

-- This session's shots whose entry differs from the saved one: {num, entry}
local function review_changes(r)
    local out = {}
    for num in pairs(r.touched) do
        local shot
        for _, s in ipairs(state.shots or {}) do if s.num == num then shot = s; break end end
        if shot then
            local e, b = review_entry(r, shot), r.base[num]
            local same
            if not e or not b then same = (e == nil and b == nil)
            else same = slash(abs_file(r, b.file)) == slash(e.file) and b.mark == e.mark
                        and (b.comp == true) == (e.comp == true)
                        and (b.note or "") == (e.note or "") and b.by == e.by
                        and session.inputs_json(b.inputs) == session.inputs_json(e.inputs) end
            if not same then out[#out + 1] = {num = num, entry = e} end
        end
    end
    table.sort(out, function(a, b) return a.num < b.num end)
    return out
end

local function short_line(s) return #s > 118 and (s:sub(1, 115) .. "…") or s end
-- a script line the save card always keeps: a warning, or a next step the
-- project prints for the marked shots ("to reroll: /go 07", "both in one run: ...")
local function must_show(line)
    return line:upper():find("WARNING", 1, true) ~= nil or line:match("^%s*to %a[%w%- ]*:") ~= nil
           or line:match("^%s*both in one run:") ~= nil or line:match("^%s*comp after the roll:") ~= nil
end

local function show_result(r)
    local res = r.result
    r.result = nil
    if not res then return end
    if res.ok then   -- it went through: the saving card listed the shots; no card to dismiss
        osd(res.lines[1] or "review saved", 2.5)
        if res.done then res.done(true) else render(true) end
        return
    end
    -- room for 16 lines: warnings, failures and the next steps ("to reroll: ...")
    -- first claim, then the newest of the rest
    local keep, room = {}, 16
    for i, line in ipairs(res.lines) do
        if must_show(line) or line:find("FAILED", 1, true) or line:find("not run:", 1, true) then
            keep[i] = true; room = room - 1
        end
    end
    for i = #res.lines, 1, -1 do
        if room <= 0 then break end
        if not keep[i] then keep[i] = true; room = room - 1 end
    end
    local lines = {}
    for i, line in ipairs(res.lines) do
        if keep[i] then lines[#lines + 1] = short_line(line) end
    end
    open_modal({
        title = res.ok and "Review saved" or "Saved, with a problem", title_fs = 64,
        lines = lines,
        choices = {{label = "OK", keys = {"o", "O", "y", "Y", "SPACE"}}},
        default = 1, cancel = 1,
        done = function() if res.done then res.done(res.ok) else render(true) end end,
    })
end

-- Save: the choices file first, then the project's scripts, then reload the XML
-- they rebuilt and show what they said. done() runs when the card is dismissed.
local function save_review(done)
    local r = current_review()
    if not r or review_busy or in_preview(r) then return end
    if not lock.mine(r.xml) then   -- the lock went to someone else since this opened
        local other = lock.other(r.xml)
        if other then
            r.preview = other
            osd("Not saved: " .. lock.who(other) .. ".", 8)
            render(true)
            return
        end
        lock.take(r.xml)
    end
    local changes = review_changes(r)
    if #changes == 0 and not (r.session_imported and #r.session_imported > 0) then
        if done then done(true) else osd("nothing to save", 1.5) end
        return
    end
    -- read it again and change only this session's shots; written in place
    local shots = read_selects(r)
    for _, c in ipairs(changes) do
        local rel = c.entry and rel_file(r, c.entry.file)
        if c.entry and not rel then
            osd("not saved: " .. name_of(c.entry.file) .. " is outside " .. name_of(r.root), 4); return
        end
        shots[c.num] = c.entry and {file = rel, mark = c.entry.mark, comp = c.entry.comp, note = c.entry.note,
                                    by = c.entry.by, inputs = c.entry.inputs and slack.place_frames(r, c.num, c.entry.inputs)} or nil
    end
    -- the notes files imported so far: the ones already listed and this session's
    local imported, seen = {}, {}
    for _, list in ipairs({notes.read_imported(r), r.session_imported or {}}) do
        for _, f in ipairs(list) do if not seen[f] then seen[f] = true; imported[#imported + 1] = f end end
    end
    if not write_file(selects_path(r), selects_text(shots, imported)) then
        osd("could not write " .. name_of(selects_path(r)), 4); return
    end
    r.base, r.marks, r.touched, r.cleared, r.notes, r.by, r.inputs = read_selects(r), {}, {}, {}, {}, {}, {}
    r.base_imported, r.session_imported = imported, {}
    r.rescan = true   -- the scripts may have made new versions
    local report = {string.format("%s: %d shot%s changed", name_of(selects_path(r)), #changes, #changes == 1 and "" or "s")}
    -- the changed shots, for the saving card: "07  ·  run 12  ·  re-roll, comp, note  ·  driver, start frame"
    local changed = {}
    for _, c in ipairs(changes) do
        local e = c.entry
        if not e then changed[#changed + 1] = c.num .. "  ·  choice cleared"
        else
            local ri = rung_info(abs_file(r, rel_file(r, e.file) or ""))
            local what = {}
            if e.mark then what[#what + 1] = (e.mark == "reroll" and "re-roll") or (e.mark == "recirculate" and "re-circulate") or e.mark end
            if e.comp then what[#what + 1] = "comp" end
            if (e.note or "") ~= "" then what[#what + 1] = "note" end
            local ins = {}
            for _, k in ipairs({"driver", "start", "end"}) do
                if e.inputs and e.inputs[k] then
                    ins[#ins + 1] = k == "driver" and (e.inputs[k].kind == "depth" and "depth driver" or "driver") or (k .. " frame")
                end
            end
            local line = c.num .. "  ·  " .. (ri and rung_label(ri):gsub("^%S+%s*", "") or name_of(e.file))
            if #what > 0 then line = line .. "  ·  " .. table.concat(what, ", ") end
            if #ins > 0 then line = line .. "  ·  " .. table.concat(ins, ", ") end
            changed[#changed + 1] = line
        end
    end
    msg.info("review saved: " .. selects_path(r))

    local cmds = {}
    for cmd in o.review_save_cmds:gmatch("[^;]+") do
        if cmd:match("%S") then cmds[#cmds + 1] = trim(cmd) end
    end
    local all_ok = true
    review_busy = true
    mp.set_property_bool("pause", true)
    clear_overlay()
    hide_osc(true)
    local t0 = mp.get_time()
    local stage = "updating the folders"   -- what the card says is happening now
    local tick = mp.add_periodic_timer(0.5, function()
        draw_saving(stage, math.floor(mp.get_time() - t0), "", changed)
    end)
    draw_saving(stage, 0, "", changed)

    local function finish()
        tick:kill()
        review_busy = false
        msg.info(string.format("review save: %.1fs in all", mp.get_time() - t0))
        -- quitting (Yes at the quit prompt) and it went through: no reload, no
        -- frame flashing back; the card stays until mpv closes (or renders the video)
        if done and all_ok then return done(true) end
        r.result = {ok = all_ok, lines = report, done = done}
        -- the XML was rebuilt from the saved choices: it carries them now
        if all_ok and #cmds > 0 then picks[r.xml] = nil end
        session.relist()   -- the project's scripts may have copied files (a final)
        -- the card stays over the reload and goes once the rebuilt review shows its
        -- frame, so the old frame doesn't flash back in between
        stage = "reloading the review"
        draw_saving(stage, math.floor(mp.get_time() - t0), "", changed)
        local gone = false
        local function reveal()
            if gone then return end
            gone = true
            mp.unregister_event(reveal)
            saving_overlay:remove()
            hide_osc(false)
            render(true)
        end
        mp.register_event("playback-restart", reveal)
        mp.add_timeout(10, reveal)   -- whatever happens, the card doesn't stay
        pending_action = {kind = "choose", xml = r.xml, notice = "review saved",
                          pos = mp.get_property_number("time-pos") or 0}
        mp.commandv("loadfile", state.path, "replace")
    end
    local function step(i)
        local cmd = cmds[i]
        if not cmd then return finish() end
        local label = name_of((cmd:match("^%S+")))
        stage = "running " .. label
        draw_saving(stage, math.floor(mp.get_time() - t0), "", changed)
        local t1 = mp.get_time()
        local args, why = tools.args(r.root, cmd)
        if not args then
            all_ok = false
            report[#report + 1] = label .. " not run: " .. why
            return step(i + 1)
        end
        tools.run_async(args, function(res)
            local ok, lines = tool_result(res)
            msg.info(string.format("review save: %s took %.1fs", label, mp.get_time() - t1))
            if not ok then
                all_ok = false
                report[#report + 1] = label .. " FAILED: " .. tools.failure(res)
            end
            -- its last lines, and every warning wherever it was printed
            for j, line in ipairs(lines) do
                if j > #lines - 8 or must_show(line) then report[#report + 1] = line end
            end
            step(i + 1)
        end)
    end
    if #cmds == 0 then report[#report + 1] = "no scripts configured: the folders were not updated" end
    step(1)
end

local function open_review_prompt(r)
    local n = #review_changes(r)
    local video = {label = "Also save an .mp4 of the review", on = false, keys = {"v", "V"}}
    open_modal({
        title = "Save changes?", title_fs = 96,
        lines = {string.format("%d shot%s chosen or marked this session.  Yes saves the choices and updates the folders.  " ..
                               "No forgets them.", n, n == 1 and "" or "s")},
        choices = {{label = "Yes", keys = {"y", "Y"}}, {label = "No", keys = {"n", "N"}},
                   {label = "Cancel", keys = {"c", "C"}}},
        check = video,
        default = 2, cancel = 3,
        hint = "Y  yes   ·   N  no   ·   C or Esc  cancel   ·   V  video   ·   ← →  then Enter",
        done = function(i)
            if i == 1 then
                save_review(function(ok)
                    -- the video of the rebuilt XML, beside it; only when the save went through
                    if video.on and ok then
                        export.xml = r.xml
                        run_export(function() mp.command("quit") end)
                    else
                        if video.on then msg.warn("video not rendered: the save had a problem") end
                        mp.command("quit")
                    end
                end)
            elseif i == 2 then mp.command("quit")
            else render(true) end
        end,
    })
end

