local slack = {}   -- one table: the script's main chunk is near Lua's limit of 200 locals
function slack.frame()
    local fps = state.fps or mp.get_property_number("container-fps") or 30
    return 0.5 / fps
end

-- How far before a shot's start a time still counts as that shot. A scanned
-- video's cut times can sit a little after the frame they belong to: half a
-- frame. In an assembly each shot's first frame lands exactly on (a hair after)
-- its start, and a take at another frame rate (a 24 fps take in a 23.976 cut)
-- can put the previous shot's last frame inside that half frame: 1 ms, so that
-- frame stays the previous shot's.
function slack.shot()
    return state.assembly and 0.001 or slack.frame()
end

-- where a jump to shot s lands: an assembly just inside the shot (so only its
-- own frames are in play), a scanned video half a frame before the cut
function slack.target(s)
    if state.assembly then return s.t + 0.0005 end
    return math.max(0, s.t - slack.frame())
end

-- A shot whose take was switched loops on its own: Space plays it over and over
-- (mpv's A-B loop, over the shot's frames). Moving to another shot lets the
-- timeline run on again. slack.loop = {xml, idx} of that shot, or nil
function slack.set_loop(s)
    if s then
        local half = 0.5 / ((state.fps and state.fps > 0) and state.fps or 24)
        mp.set_property_number("ab-loop-a", s.t)
        mp.set_property_number("ab-loop-b", s.t + math.max(s.len - half, half))
    else
        mp.set_property("ab-loop-a", "no")
        mp.set_property("ab-loop-b", "no")
    end
end
function slack.unloop()
    if not slack.loop then return end
    slack.loop = nil
    slack.set_loop(nil)
end
-- each load of the XML (a take swap reloads it): loop that shot again, if it's still there
mp.register_event("file-loaded", function()
    local lp, asm = slack.loop, state.assembly
    if not lp then return end
    local s = asm and asm.xml == lp.xml and asm.shots[lp.idx]
    if s then slack.set_loop(s) else slack.unloop() end
end)

-- Leaving a shot whose slot shows a take other than its select puts the select
-- back, so the cut always plays the selects. True when a reload is needed.
-- slack.here = {xml, idx}: the shot that was on screen
function slack.snap_back(left)
    local asm = state.assembly
    local r = asm and reviews[asm.xml]
    local s = asm and asm.shots[left]
    local mine = s and s.num and picks[asm.xml] and picks[asm.xml][s.num]
    if not r or not mine or not session.select_of then return false end
    local sel = session.select_of(r, s)
    if sel and slash(mine) == sel then return false end
    if not sel or sel == slash(s.xml_orig or "") then picks[asm.xml][s.num] = nil else picks[asm.xml][s.num] = sel end
    return true
end

local function jump_to(i)
    local s = state.shots[i]
    if slack.loop and slack.loop.idx ~= i then slack.unloop() end   -- another shot: the timeline runs on
    -- an assembly stops on the shot, so Up / Down and the marks act on the shot
    -- on screen instead of wherever playback has rolled on to
    if state.assembly then mp.set_property_bool("pause", true) end
    mp.commandv("seek", tostring(slack.target(s)), "absolute+exact")
    if state.assembly then
        osd(string.format("%d/%d  %s", i, #state.shots, s.name or ""), 1)
    end
end

-- Every shot is a stop, rejected and missing ones included (so they can be seen and undone)
local function usable(i) return state.shots[i] ~= nil end

local function shot_next()
    local shots = state.shots
    if not shots then mp.command("frame-step"); return end
    local pos = mp.get_property_number("time-pos") or 0
    local h = slack.shot()
    for i, s in ipairs(shots) do
        if usable(i) and s.t > pos + h then jump_to(i); return end
    end
    if scan and scan.path == state.path then osd("scanning shots…", 1); return end
    for i = 1, #shots do if usable(i) then jump_to(i); return end end
end

local function shot_prev()
    local shots = state.shots
    if not shots then mp.command("frame-back-step"); return end
    local pos = mp.get_property_number("time-pos") or 0
    local h = slack.shot()
    local cur = 0
    for i, s in ipairs(shots) do if s.t <= pos + h then cur = i end end
    if usable(cur) and pos - shots[cur].t > 0.5 then jump_to(cur); return end
    for i = cur - 1, 1, -1 do if usable(i) then jump_to(i); return end end
    for i = #shots, 1, -1 do if usable(i) then jump_to(i); return end end
end

