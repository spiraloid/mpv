local function clear_overlay()
    buttons = {}
    if overlay_key then overlay:remove(); overlay_key = nil end
    if update_hover then update_hover(nil) end
end

local function render(force)
    if export.running then clear_overlay(); return end
    local i = state.assembly and current_shot_index()
    local shot = i and state.shots[i]
    local d = mp.get_property_native("osd-dimensions")
    if not shot or not d or not d.w or d.w <= 0 then clear_overlay(); return end
    local key = table.concat({i, d.w, d.h, d.ml, d.mt, d.mr, d.mb, tostring(hovered),
                              tostring(shot.approved), tostring(approving), tostring(overlay_on),
                              tostring(mp.get_property_bool("pause"))}, ":")
    if key == overlay_key and not force then return end

    -- video rectangle inside the window (letterbox margins)
    local vx0, vy0 = d.ml, d.mt
    local vw, vh = d.w - d.ml - d.mr, d.h - d.mt - d.mb
    local k = vh / 1080
    local events = {}
    if shot.retired then rejected_events(events, vx0, vy0, vw, vh, k, "REJECTED")
    elseif shot.missing then rejected_events(events, vx0, vy0, vw, vh, k, "MISSING") end
    buttons = {}
    if overlay_on then
        label_events(events, shot, vx0, vy0, vw, vh, k)
        button_events(events, shot, vx0, vy0, vw, k)
    end
    if #events == 0 then clear_overlay(); return end
    overlay_key = key
    overlay.res_x, overlay.res_y = d.w, d.h
    overlay.data = table.concat(events, "\n")
    overlay:update()
    -- buttons can appear under a mouse that isn't moving (next shot, reload)
    if update_hover then update_hover(mp.get_property_native("mouse-pos")) end
end

