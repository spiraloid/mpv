-- ── export: render the assembly to <xml name>.mp4 ────────────────────────────
-- Matches the burned-in dailies: H.264 High, CRF 18 (medium), the edit's frame
-- rate, AAC at 48 kHz, with the shot labels and REJECTED / MISSING cards burned
-- in. A hidden mpv builds the same assembly from the XML on disk; in that copy
-- this script writes the labels as an ASS subtitle track (vo encoders burn in
-- subtitles, not OSD overlays). Written to a hidden temp file, then renamed over
-- the old video.

local function ass_time(s)
    local cs = math.max(0, math.floor(s * 100))
    local f = math.floor
    return string.format("%d:%02d:%02d.%02d", f(cs / 360000), f(cs / 6000) % 60, f(cs / 100) % 60, cs % 100)
end

-- In the exporter: burn the labels in as subtitles
add_burn_in = function()
    local w, h = mp.get_property_number("width", 1920), mp.get_property_number("height", 1080)
    local k = h / 1080
    local lines = ass_header(w, h)
    for _, shot in ipairs(state.shots or {}) do
        local events = {}
        if shot.retired then rejected_events(events, 0, 0, w, h, k, "REJECTED")
        elseif shot.missing then rejected_events(events, 0, 0, w, h, k, "MISSING") end
        label_events(events, shot, 0, 0, w, h, k)
        for _, e in ipairs(events) do
            lines[#lines + 1] = string.format("Dialogue: 0,%s,%s,Default,,0,0,0,,%s",
                ass_time(shot.t), ass_time(shot.t + shot.len), e)
        end
    end
    local ass = utils.join_path(temp_dir(), string.format("mpv_burnin_%d.ass", utils.getpid()))
    if write_file(ass, table.concat(lines, "\n") .. "\n") then
        mp.commandv("sub-add", ass, "select")
        mp.register_event("shutdown", function() os.remove(ass) end)
    end
end

local function export_target(xml) return (xml:gsub("%.[xX][mM][lL]$", "")) .. ".mp4" end

local function export_args(xml, out)
    local cfg = (mp.command_native({"expand-path", "~~/"}) or ""):gsub("[/\\]+$", "")
    return {
        mpv_binary(), "--config-dir=" .. cfg, "--load-scripts=yes", "--no-terminal", "--osc=no",
        "--loop-file=no", "--loop-playlist=no", "--pause=no", "--idle=no", "--keep-open=no",
        "--o=" .. out, "--of=mp4", "--ovc=libx264",
        "--ovcopts=crf=18,preset=medium,profile=high,colorspace=bt709,color_primaries=bt709,color_trc=bt709",
        "--oac=aac", "--oacopts=b=64k", "--audio-samplerate=48000",
        "--audio-channels=" .. (export.channels == 1 and "mono" or "auto-safe"),
        "--sub-ass-override=no", "--sub-visibility=yes", "--", xml,
    }
end

local function export_tmp(target) return utils.join_path(dir_of(target), "." .. name_of(target) .. ".export.mp4") end

local function finish_export(xml, ok)
    local target = export_target(xml)
    local tmp = export_tmp(target)
    if ok and exists(tmp) then
        os.remove(target)
        if os.rename(tmp, target) then
            msg.info("exported " .. target)
            return true
        end
    end
    os.remove(tmp)
    msg.error("export failed: " .. target)
    return false
end

-- Interactive: render with an OSD clock, then call done(ok)
-- A full-frame "SAVING…" card while the render runs, above everything else
local saving_overlay = mp.create_osd_overlay("ass-events")
saving_overlay.z = 1000

local function draw_saving(name, secs)
    local d = mp.get_property_native("osd-dimensions") or {w = 1920, h = 1080}
    local w, h = d.w or 1920, d.h or 1080
    local k = h / 1080
    saving_overlay.res_x, saving_overlay.res_y = w, h
    saving_overlay.data = table.concat({
        string.format("{\\an7\\pos(0,0)\\p1\\bord0\\shad0\\1c&H000000&\\1a&H30&}m 0 0 l %d 0 %d %d 0 %d{\\p0}", w, w, h, h),
        string.format("{\\an5\\pos(%.1f,%.1f)\\bord0\\shad0\\b1\\q2\\1c&HFFFFFF&\\1a&H00&\\fs%.1f\\fsp%.1f}SAVING…",
            w / 2, h / 2 - 20 * k, 150 * k, 6 * k),
        string.format("{\\an5\\pos(%.1f,%.1f)\\bord0\\shad0\\q2\\1c&HC0C0C0&\\1a&H00&\\fs%.1f}%s  ·  %ds  ·  press again to quit without the video",
            w / 2, h / 2 + 90 * k, 30 * k, ass_text(name), secs),
    }, "\n")
    saving_overlay:update()
end

local function run_export(done)
    local xml = export.xml
    local tmp = export_tmp(export_target(xml))
    os.remove(tmp)
    local t0 = mp.get_time()
    mp.set_property_bool("pause", true)
    clear_overlay()
    local name = name_of(export_target(xml))
    draw_saving(name, 0)
    local tick = mp.add_periodic_timer(0.5, function()
        draw_saving(name, math.floor(mp.get_time() - t0))
    end)
    export.running = mp.command_native_async(
        {name = "subprocess", args = export_args(xml, tmp), playback_only = false,
         capture_stdout = true, capture_stderr = true},
        function(ok, res)
            tick:kill()
            export.running = nil
            if export.skip then os.remove(tmp); return end
            local good = finish_export(xml, ok and res and res.status == 0)
            export.done = good
            if good then
                done(good)
            else
                saving_overlay:remove()
                osd("could not save the assembly video", 3)
                mp.add_timeout(2, function() done(good) end)
            end
        end)
end

-- ── exit prompt: Save changes? Yes / No / Cancel ──────────────────────────────

-- Put the disk back the way it was when the XMLs were first opened: undo every
-- move and copy in reverse, then restore each XML (and drop a .bak this session
-- made). Runs at shutdown, after mpv has let go of the files.
local function revert_session()
    local undone, failed = 0, 0
    for i = #session.journal, 1, -1 do
        local e = session.journal[i]
        if e.xml_edit then
            undone = undone + 1               -- the XML text is restored below
        elseif e.create then
            if os.remove(e.create) then undone = undone + 1 else failed = failed + 1 end
        elseif exists(e.to) and not exists(e.from) then
            if mkdir_p(dir_of(e.from)) and move_file(e.to, e.from) then
                undone = undone + 1
                -- tidy the folder the file left: retired/ subfolders, or a run folder
                local dir = dir_of(e.to)
                local ri = rung_info(e.to)
                if slash(dir):find("/retired/", 1, true) or name_of(dir) == "retired" then
                    while true do
                        remove_empty_dir(dir)
                        if exists(dir) or name_of(dir) == "retired" then break end
                        dir = dir_of(dir)
                    end
                elseif ri and slash(dir) ~= ri.shots .. "/" .. ri.rung then
                    remove_empty_dir(dir)
                end
            else
                failed = failed + 1
                msg.error("could not move back " .. e.to .. " -> " .. e.from)
            end
        else
            failed = failed + 1
            msg.error("could not move back (missing or blocked) " .. e.to .. " -> " .. e.from)
        end
    end
    for xml, snap in pairs(session.snap) do
        if read_file(xml) ~= snap.text then write_file(xml, snap.text) end
        if not snap.bak then os.remove(xml .. ".bak") end
    end
    session.journal = {}
    msg.info(string.format("put back %d change(s)%s", undone, failed > 0 and (", " .. failed .. " failed") or ""))
end

-- A full-frame card with a title, a few lines and buttons; used by the exit prompt
-- and the validation check. spec = {title, lines, choices = {{label, keys}},
-- default, cancel, hint, done(i)}.
local modal = {rects = {}}
local modal_overlay = mp.create_osd_overlay("ass-events")
modal_overlay.z = 900
local modal_keys = {}

local function draw_modal()
    local spec = modal.spec
    if not spec then return end
    local d = mp.get_property_native("osd-dimensions") or {w = 1920, h = 1080}
    local w, h = d.w or 1920, d.h or 1080
    local k = h / 1080
    local lines = spec.lines or {}
    local line_h = 34 * k
    local top = h / 2 - (150 + #lines * 34 / 2) * k
    local ev = {
        string.format("{\\an7\\pos(0,0)\\p1\\bord0\\shad0\\1c&H000000&\\1a&H30&}m 0 0 l %d 0 %d %d 0 %d{\\p0}", w, w, h, h),
        string.format("{\\an5\\pos(%.1f,%.1f)\\bord0\\shad0\\b1\\q2\\1c&HFFFFFF&\\1a&H00&\\fs%.1f}%s",
            w / 2, top, (spec.title_fs or 80) * k, ass_text(spec.title)),
    }
    local y = top + 80 * k
    for _, line in ipairs(lines) do
        ev[#ev + 1] = string.format("{\\an5\\pos(%.1f,%.1f)\\bord0\\shad0\\q2\\1c&HC8C8C8&\\1a&H00&\\fs%.1f}%s",
            w / 2, y, 25 * k, ass_text(line))
        y = y + line_h
    end
    local n = #spec.choices
    local bw, bh, gap = (spec.button_w or 240) * k, 84 * k, 36 * k
    local x = w / 2 - (n * bw + (n - 1) * gap) / 2
    y = y + 30 * k
    modal.rects = {}
    for i, ch in ipairs(spec.choices) do
        local sel = i == modal.sel
        ev[#ev + 1] = string.format(
            "{\\an7\\pos(0,0)\\p1\\bord%.2f\\shad0\\1c&H%s&\\1a&H%s&\\3c&HFFFFFF&\\3a&H%s&}m %.0f %.0f l %.0f %.0f %.0f %.0f %.0f %.0f{\\p0}",
            2 * k, sel and "FFFFFF" or "3A3A3A", sel and "00" or "30", sel and "00" or "90",
            x, y, x + bw, y, x + bw, y + bh, x, y + bh)
        ev[#ev + 1] = string.format("{\\an5\\pos(%.1f,%.1f)\\bord0\\shad0\\b1\\q2\\1c&H%s&\\1a&H00&\\fs%.1f}%s",
            x + bw / 2, y + bh / 2, sel and "000000" or "FFFFFF", 38 * k, ass_text(ch.label))
        modal.rects[i] = {x, y, x + bw, y + bh}
