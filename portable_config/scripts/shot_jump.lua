-- Imported notes ---------------------------------------------------------------
-- i brings in a notes file from review_notes_dir (the project writes one per
-- recorded review: {"reviewer", "source", "shots": {"07": {"file", "label",
-- "note", "mark"}}, "general": [...]}), the newest one not imported yet; i again
-- takes the next older. A note whose shot still plays the version it was made on,
-- and has no note or state yet, goes straight in, as if typed. The rest wait:
-- the shot has its own note or state, or its select moved on since (stale).
-- Tab / Shift+Tab step through them: Enter accepts (onto the version showing),
-- n edits the text, r / c / m / a choose the state, x skips, Esc stops.
-- Save records the file in selects.json's "imported" so it isn't offered again.
function notes.read_imported(r)
    local text = r.shots and read_file(selects_path(r))
    local j = text and utils.parse_json(text)
    local out = {}
    if type(j) == "table" and type(j.imported) == "table" then
        for _, f in ipairs(j.imported) do if type(f) == "string" then out[#out + 1] = f end end
    end
    return out
end

-- Seen: which versions someone has watched. A version counts as seen once it has
-- been on screen (drawn, about a quarter second) in a review, and the editor's mpv records it in
-- <shots>/seen.json ({"since", "files": {path: {"at", "by"}}}, written in place a
-- few seconds later). Files older than "since" (when the file was first made)
-- count as seen, so only generations made after it can be new. A shot with
-- versions nobody has seen shows a green bell and "N new" over its label.
function notes.seen_path(r) return utils.join_path(native_seps(r.shots), "seen.json") end

function notes.seen_write(r)
    local j = utils.parse_json(read_file(notes.seen_path(r)) or "")
    if type(j) == "table" and type(j.files) == "table" then   -- keep whatever is there
        for f, v in pairs(j.files) do if r.seen.files[f] == nil then r.seen.files[f] = v end end
        r.seen.since = math.min(r.seen.since, tonumber(j.since) or r.seen.since)
    end
    local keys, rows = {}, {}
    for f in pairs(r.seen.files) do keys[#keys + 1] = f end
    table.sort(keys)
    for _, f in ipairs(keys) do
        local v = type(r.seen.files[f]) == "table" and r.seen.files[f] or {}
        rows[#rows + 1] = string.format('  %s: {"at": %d, "by": %s}', json_str(f), tonumber(v.at) or 0, json_str(tostring(v.by or "")))
    end
    write_file(notes.seen_path(r), string.format('{\n "since": %d,\n "files": {\n%s\n }\n}\n',
        r.seen.since, table.concat(rows, ",\n")))
end

function notes.seen_load(r)
    local j = utils.parse_json(read_file(notes.seen_path(r)) or "")
    -- everything made before the day seen.json was started counts as seen
    local function day_start(t) local d = os.date("*t", t); d.hour, d.min, d.sec = 0, 0, 0; return os.time(d) end
    if type(j) == "table" and type(j.files) == "table" then
        local since = tonumber(j.since) or 0
        r.seen = {since = since > 0 and day_start(since) or 0, files = j.files}
        if r.seen.since ~= since and not r.preview then notes.seen_write(r) end
    else
        r.seen = {since = day_start(os.time()), files = {}}
        if not r.preview then notes.seen_write(r) end
    end
end

-- the versions of each shot nobody has seen (originals, as Up / Down lists them)
function notes.unseen_scan(r)
    r.unseen = {}
    local cache = session.listing()
    for _, shot in ipairs(state.shots or {}) do
        if shot.rung and shot.num and not r.unseen[shot.num] then
            -- one picture is one version, whichever rungs hold it: a byte copy (a pick,
            -- a final, a copy back into a lower rung) goes with every file it matches,
            -- and the group counts as seen if any of them was seen, was picked in a
            -- review (the choices file names it), or was made before "since".
            -- Generations only: no plates, nothing retired.
            local u = {}
            local rows = shot_versions(shot.rung.shots, shot.rung.nn, cache)
            local chosen = r.base[shot.num] and slash(r.base[shot.num].file or "") or nil
            local function seenish(x)
                local rel = rel_file(r, x.path)
                return (rel and (r.seen.files[rel] ~= nil or rel == chosen)) or (x.mtime or 0) <= r.seen.since
            end
            local gid = 0
            for _, v in ipairs(rows) do
                local rel = rel_file(r, v.path)
                if rel and v.letter >= "C" and not v.retired and not u[rel] then
                    local group, any_seen = {v}, seenish(v)
                    for _, x in ipairs(rows) do
                        if x ~= v and same_file(x, v) then group[#group + 1] = x; any_seen = any_seen or seenish(x) end
                    end
                    if not any_seen then
                        gid = gid + 1
                        for _, x in ipairs(group) do
                            local xr = rel_file(r, x.path)
                            if xr then u[xr] = gid end
                        end
                    end
                end
            end
            r.unseen[shot.num] = u
        end
    end
end

B.unseen = function(shot)
    local r = current_review and current_review()
    if not r or not r.unseen or not shot.num then return 0 end
    local n, groups = 0, {}
    for _, g in pairs(r.unseen[shot.num] or {}) do
        if not groups[g] then groups[g] = true; n = n + 1 end
    end
    return n
end

-- every quarter second: what's on screen, and for how long
function notes.seen_tick()
    local r = current_review()
    notes.ticks = (notes.ticks or 0) + 1
    if r and r.seen and notes.seen_dirty and notes.ticks % 12 == 0 then
        notes.seen_dirty = false
        notes.seen_write(r)
    end
    if not r or r.preview or not r.seen or review_busy or export.prompting then notes.watch = nil; return end
    local shot = current_shot()
    local f = shot and shot.rung and (shot.file or shot.play)
    local rel = f and rel_file(r, f)
    if not rel then notes.watch = nil; return end
    local w = notes.watch
    if not w or w.rel ~= rel then notes.watch = {rel = rel, t = mp.get_time()}; return end
    if mp.get_time() - w.t >= 0.2 then   -- drawn: seen
        -- a slot playing a copy (a final) shows its original: both count as seen
        notes.mark_seen(r, shot.num, rel, shot.play and rel_file(r, shot.play))
    end
end

-- record a version as seen, and take its picture (every copy of it) off the shot's new count
function notes.mark_seen(r, num, rel, also)
    if not r or r.preview or not r.seen or not rel then return end
    local changed = false
    for _, f in ipairs({rel, also}) do
        if f and r.seen.files[f] == nil then
            r.seen.files[f] = {at = os.time(), by = notes.reviewer(r)}
            changed = true
        end
    end
    local u = r.unseen and r.unseen[num]
    if u then
        local g = u[rel] or (also and u[also])
        if g then
            for f, x in pairs(u) do if x == g then u[f] = nil end end
            changed = true
        end
    end
    if changed then notes.seen_dirty = true; render(true) end
end

