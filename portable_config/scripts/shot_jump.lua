local function mpv_binary()
    local cfg = (mp.command_native({"expand-path", "~~/"}) or ""):gsub("[/\\]+$", "")
    local root = dir_of(cfg)
    local candidates = is_windows and {utils.join_path(root, "mpv.exe")}
        or {utils.join_path(root, "mpv"), "/opt/homebrew/bin/mpv", "/usr/local/bin/mpv"}
    for _, c in ipairs(candidates) do
        local info = utils.file_info(c)
        if info and info.is_file then return c end
    end
    -- Windows searches the running mpv.exe's folder first; never mpv.com (console)
    return is_windows and "mpv.exe" or "mpv"
end

local function temp_dir()
    return (is_windows and os.getenv("TEMP")) or os.getenv("TMPDIR") or "/tmp"
end

local function set_shots_from_cuts(cuts)
    local shots = {{t = 0}}
    for _, c in ipairs(cuts) do shots[#shots + 1] = {t = c} end
    state.shots = (#shots > 1) and shots or nil
end

local function read_scan_log()
    if not scan then return end
    local f = io.open(scan.log, "rb")
    if not f then return end
    f:seek("set", scan.offset)
    local chunk = f:read("*a") or ""
    f:close()
    scan.offset = scan.offset + #chunk
    local data = scan.buf .. chunk
    local last_nl = data:match(".*()\n")
    if last_nl then
        scan.buf = data:sub(last_nl + 1)
        data = data:sub(1, last_nl)
    else
        scan.buf = data
        return
    end
    local added = false
    for tm in data:gmatch("lavfi%.scd%.time: ([%d%.]+)") do
        local v = tonumber(tm)
        if v and v > 0 then scan.cuts[#scan.cuts + 1] = v; added = true end
    end
    if added and state.path == scan.path then
        table.sort(scan.cuts)
        set_shots_from_cuts(scan.cuts)
    end
end

local function stop_scan()
    if scan_timer then scan_timer:kill(); scan_timer = nil end
    if scan then
        scan.aborted = true
        if scan.poll then scan.poll:kill() end
        if scan.token then mp.abort_async_command(scan.token) end
        -- Windows keeps the log locked until the killed child has exited
        local log = scan.log
        if not os.remove(log) then mp.add_timeout(1, function() os.remove(log) end) end
        scan = nil
    end
end

local function sidecar_path(video)
    return (video:gsub("%.[^%./\\]+$", "")) .. ".xml"
end

local function write_sidecar(video, cuts, info)
    local fps = info.fps
    local tb = round(fps)
    local ntsc = math.abs(fps - tb) > 0.01
    local total = round(info.duration * fps)
    local frames = {0}
    for _, c in ipairs(cuts) do
        local f = round(c * fps)
        if f > frames[#frames] and f < total then frames[#frames + 1] = f end
    end
    if #frames < 2 then return end
    frames[#frames + 1] = total
    local rate = string.format("<rate><timebase>%d</timebase><ntsc>%s</ntsc></rate>", tb, ntsc and "TRUE" or "FALSE")
    local name = name_of(video)
    local base = name:gsub("%.[^%.]+$", "")
    local out = {
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!DOCTYPE xmeml>',
        string.format('<!-- %s (scdet threshold %s) -->', GENERATED_MARK, tostring(o.threshold)),
        '<xmeml version="4">',
        ' <sequence id="sequence-1">',
        '  <name>' .. xml_escape(base) .. '</name>',
        '  <duration>' .. total .. '</duration>',
        '  ' .. rate,
        '  <media>',
        '   <video>',
        string.format('    <format><samplecharacteristics><width>%d</width><height>%d</height>%s</samplecharacteristics></format>',
            info.w or 0, info.h or 0, rate),
        '    <track>',
    }
    for i = 1, #frames - 1 do
        local s, e = frames[i], frames[i + 1]
        local file
        if i == 1 then
            file = string.format('<file id="file-1"><name>%s</name><pathurl>%s</pathurl>%s<duration>%d</duration></file>',
                xml_escape(name), xml_escape(pct_encode(name)), rate, total)
        else
            file = '<file id="file-1" />'
        end
        out[#out + 1] = string.format(
            '     <clipitem id="clipitem-%d"><name>shot %03d</name><duration>%d</duration>%s' ..
            '<start>%d</start><end>%d</end><in>%d</in><out>%d</out>%s</clipitem>',
            i, i, total, rate, s, e, s, e, file)
    end
    for _, l in ipairs({'    </track>', '   </video>', '  </media>', ' </sequence>', '</xmeml>', ''}) do
        out[#out + 1] = l
    end
    local p = sidecar_path(video)
    if exists(p) then return end
    if write_new_file(p, table.concat(out, "\n")) then msg.info("wrote " .. p) end
end

local function start_scan(path)
    stop_scan()
    local log = utils.join_path(temp_dir(), string.format("mpv_shots_%d_%d.log", utils.getpid(), os.time()))
    local s = {path = path, log = log, offset = 0, buf = "", cuts = {}}
    scan = s
    local args = {
        mpv_binary(), "--no-config", "--no-terminal", "--load-scripts=no", "--osc=no", "--ytdl=no",
        "--vo=null", "--ao=null", "--aid=no", "--sid=no", "--untimed", "--loop-file=no",
        "--pause=no", "--idle=no", "--force-window=no",
        "--vf=lavfi=[scale=320:-2:flags=fast_bilinear,scdet=threshold=" .. tostring(o.threshold) .. "]",
        "--log-file=" .. log, "--", path,
    }
    local info = {
        fps = mp.get_property_number("container-fps") or mp.get_property_number("estimated-vf-fps") or 30,
        duration = mp.get_property_number("duration") or 0,
        w = mp.get_property_number("video-params/w") or mp.get_property_number("width"),
        h = mp.get_property_number("video-params/h") or mp.get_property_number("height"),
    }
    s.poll = mp.add_periodic_timer(0.5, read_scan_log)
    s.token = mp.command_native_async({name = "subprocess", args = args, playback_only = false,
                                       capture_stdout = false, capture_stderr = false},
        function(success, result, err)
            if s.aborted then return end
            read_scan_log()
            s.poll:kill()
            os.remove(log)
            scan = nil
            if not success or (result and result.status ~= 0 and #s.cuts == 0) then
                msg.warn("shot scan failed: " .. tostring(err or (result and result.error_string)))
                return
            end
            table.sort(s.cuts)
            scanned[path] = s.cuts
            if state.path == path then
                set_shots_from_cuts(s.cuts)
                if #s.cuts > 0 then osd((#s.cuts + 1) .. " shots", 1) end
            end
            if #s.cuts > 0 and o.write_xml and not exists(sidecar_path(path)) then
                write_sidecar(path, s.cuts, info)
            end
        end)
end

-- ── sidecar (video with an XML beside it) ─────────────────────────────────────

local function load_sidecar(path)
    local xp = sidecar_path(path)
    local text = exists(xp) and read_file(xp)
    if not text or not text:find("<xmeml", 1, true) then return false end
    local seq = parse_xmeml(text, dir_of(xp))
    if not seq or #seq.video == 0 then return false end
    local dur = mp.get_property_number("duration")
    if seq.duration and dur then
        local diff = math.abs(seq.duration / seq.fps - dur)
        if diff > math.max(2 / seq.fps, 0.1) then
            msg.warn(string.format("ignoring %s: sequence is %.2fs, video is %.2fs", xp, seq.duration / seq.fps, dur))
            return false
        end
    end
    local starts, seen = {}, {}
    for _, c in ipairs(seq.video) do
        if c.start and c.start >= 0 and not seen[c.start] then
            seen[c.start] = true
            starts[#starts + 1] = c.start
        end
    end
    table.sort(starts)
    local shots = {}
    if starts[1] ~= 0 then shots[1] = {t = 0} end
    for _, f in ipairs(starts) do shots[#shots + 1] = {t = f / seq.fps} end
    state.shots = (#shots > 1) and shots or nil
    state.fps = seq.fps
    return true
end

