function notes.step(dir)
    local r = current_review()
    if not r or review_busy or export.prompting or in_preview(r) then return end
    if notes.box then notes.close(true) end
    local order = notes.order(r)
    if #order == 0 then osd("no imported notes: i imports one", 2); return end
    local cur = current_shot()
    local here = 0
    for i, num in ipairs(order) do if cur and num == cur.num then here = i end end
    local target
    if not r.step and here > 0 and not r.imported[order[here]].done then
        target = order[here]   -- the shot on screen has one waiting: start there
    else
        if here == 0 then here = dir > 0 and 0 or #order + 1 end
        for n = 1, #order do
            local i = (here - 1 + dir * n) % #order + 1
            if not r.imported[order[i]].done then target = order[i]; break end
        end
    end
    if not target then osd("every imported note has been reviewed", 2); notes.step_stop(); return end
    local _, idx = notes.shot_for(target)
    r.step = target
    notes.step_keys(true)
    if idx and (not cur or cur.num ~= target) then jump_to(idx) end
    mp.set_property_bool("pause", true)
    render(true)
end

-- the stepped shot, if the shot on screen is it
function notes.stepping(r, shot)
    return r and shot and r.step and r.step == shot.num and r.imported and r.imported[shot.num] or nil
end

function notes.step_accept(text)
    local r, shot = current_review(), current_shot()
    local it = notes.stepping(r, shot)
    if not it then return notes.step_stop() end
    if text then it.text = text end
    notes.apply(r, shot, it)
    it.done = true
    notes.step(1)
end

function notes.step_skip()
    local r, shot = current_review(), current_shot()
    local it = notes.stepping(r, shot)
    if not it then return end
    if it.applied then   -- it went in at import: take it back out
        r.notes[shot.num], r.marks[shot.num] = nil, nil
        if r.by then r.by[shot.num] = nil end
        it.applied = false
    end
    it.done = true
    notes.step(1)
end

function notes.step_mark(name)
    local r, shot = current_review(), current_shot()
    local it = notes.stepping(r, shot)
    if not it then return false end
    if name == "comp" then it.comp = not it.comp else it.mark = it.mark ~= name and name or nil end
    if it.applied then
        r.marks[shot.num] = {file = slash(shot.file or shot.play or ""), mark = it.mark or false, comp = it.comp or false}
        notes.touch(r, shot.num)
    end
    render(true)
    return true
end

function notes.step_edit()
    local r, shot = current_review(), current_shot()
    local it = notes.stepping(r, shot)
    if not it then return false end
    notes.edit(shot, it.text, function(text) notes.step_accept(text) end)
    return true
end

-- The row across the top: one state per shot, the set one lit, then the comp switch
review_buttons = function(shot)
    local r = current_review()
    if not r or review_busy or not shot.rung or not shot.num or shot.missing or shot.retired then return nil end
    if r.preview then return {row = true, preview = "PREVIEW  ·  " .. lock.who(r.preview) .. "  ·  nothing can be saved"} end
    if notes.mode and notes.mode.r == r then   -- select mode: the green bar instead of the row
        local m = notes.mode
        local ins = notes.inputs_of(r, m.num) or {}
        local function lab(v)
            local ri = rung_info(abs_file(r, v.file))
            return ri and rung_label(ri) or name_of(v.file)
        end
        local parts = {}
        if ins.driver then
            parts[#parts + 1] = (ins.driver.kind or "footage") .. " driver " .. lab(ins.driver) ..
                ((ins.driver.note or "") ~= "" and ("  \"" .. ins.driver.note .. "\"") or "")
        end
        for _, k in ipairs({"start", "end"}) do
            if ins[k] then parts[#parts + 1] = k .. " " .. lab(ins[k]) .. " f" .. tostring(ins[k].frame or "?") end
        end
        local dk = ins.driver and (ins.driver.kind or "footage")
        local function sub(v, frames)
            if not v then return nil end
            local t = lab(v) .. (frames and (" f" .. tostring(v.frame or "?")) or "")
            if not frames and (v.note or "") ~= "" then t = t .. "  \"" .. v.note .. "\"" end
            return t
        end
        local checks = {
            {name = "pin_depth", title = "depth driver", on = dk == "depth", sub = dk == "depth" and sub(ins.driver) or nil},
            {name = "pin_mask", title = "mask driver", on = dk == "mask" or dk == "footage",
             sub = (dk == "mask" or dk == "footage") and ((dk == "footage" and "footage: " or "") .. sub(ins.driver)) or nil},
            {name = "pin_start", title = "start frame", on = ins.start ~= nil, sub = sub(ins.start, true)},
            {name = "pin_end", title = "end frame", on = ins["end"] ~= nil, sub = sub(ins["end"], true)},
        }
        local list = {row = true, mode = {label = m.label, parts = parts, checks = checks}}
        local b = notes.box
        if b then list.box = {num = b.num, chars = b.chars, pos = b.pos, anchor = b.anchor, title = b.title} end
        return list
    end
    local cur, comp = mark_of(r, shot), notes.comp_of(r, shot)
    local list = {row = true, note = notes.of(r, shot.num), by = (cur or comp) and notes.by_of(r, shot.num) or nil}
    local it = notes.stepping(r, shot)
    if it then
        local order, k = notes.order(r), 0
        for i, num in ipairs(order) do if num == shot.num then k = i end end
        local cur_file = slash(shot.file or shot.play or "")
        local saved = r.base[shot.num] and r.base[shot.num].note or ""
        list.step = {text = it.text, k = k, n = #order, reviewer = it.reviewer,
                     stale = it.file and it.file ~= cur_file and it.label or nil,
                     saved = (saved ~= "" and saved ~= it.text) and saved or nil}
        if not it.applied then cur, comp, list.by = it.mark, it.comp, nil end   -- the row shows the state it would get
    end
    local b = notes.box
    if b and b.num == shot.num then
        list.box = {num = b.num, chars = b.chars, pos = b.pos, anchor = b.anchor, title = b.title,
                    hint = not b.title and cur == "recirculate" and notes.recirc_default(r) or nil}
    end
    if cur == "recirculate" and (list.note or "") == "" then
        local d = notes.recirc_default(r)
        if d then list.note_hint = "default: " .. d end
    end
    -- a take other than the select: its state isn't this take's, so the row greys
    local away = not it and not notes.on_select(r, shot)
    if away then
        local sel = notes.select_of(r, shot)
        local ri = sel and rung_info(sel)
        cur, comp, list.by, list.note, list.note_hint = nil, false, nil, nil, nil
        list.hint = "Enter makes this take the select" .. (ri and ("   ·   the select is " .. rung_label(ri, shot.num_text)) or "")
    else
        list.selected = true
        -- the select's pinned inputs, small under re-circulate: the driver take and its kind, the frames
        local ins = notes.inputs_of(r, shot.num)
        if ins then
            local function lab(v)
                local ri = rung_info(abs_file(r, v.file))
                return ri and rung_label(ri) or name_of(v.file)
            end
            list.inputs = {}
            if ins.driver then
                list.inputs[#list.inputs + 1] = (ins.driver.kind or "footage") .. " driver  " .. lab(ins.driver)
            end
            local fr = {}
            for _, k in ipairs({"start", "end"}) do
                if ins[k] then fr[#fr + 1] = k .. "  " .. lab(ins[k]) .. " f" .. tostring(ins[k].frame or "?") end
            end
            if #fr > 0 then list.inputs[#list.inputs + 1] = table.concat(fr, "   ·   ") end
        end
    end
    for _, m in ipairs(MARKS) do
        list[#list + 1] = {name = m.name, text = m.label, color = m.color, star = m.star, lit = cur == m.name, off = away}
        if cur == m.name then list.state = true end
    end
    -- a final isn't comped: the switch is there, greyed, and keeps what it was
    list[#list + 1] = {name = "comp", text = MARKS.comp.label, color = MARKS.comp.color, toggle = true,
                       lit = comp and cur ~= "final", off = away or cur == "final"}
    return list
end

-- The small line over the label: which version, where copies of it sit (the
-- row shows the state; only an older mark the row lacks is named here)
review_detail = function(shot)
    local r = current_review()
    if not r then return shot.detail end
    local parts = {}
    local mark = mark_of(r, shot)
    local in_row = false
    for _, m in ipairs(MARKS) do if m.name == mark then in_row = true end end
    if mark and not in_row then parts[#parts + 1] = MARK_TEXT[mark] or mark end
    if shot.detail then parts[#parts + 1] = shot.detail end
    if shot.copies and #shot.copies > 0 then parts[#parts + 1] = "in " .. table.concat(shot.copies, ", ") end
    -- pinned as another select's input
    local here, done = rel_file(r, shot.file or shot.play or ""), {}
    for _, s in ipairs(state.shots or {}) do
        if s.num and not done[s.num] then
            done[s.num] = true
            for k, v in pairs(notes.inputs_of(r, s.num) or {}) do
                if here and v.file == here then
                    parts[#parts + 1] = (k == "driver" and "driver" or (k .. " frame")) .. " for " .. s.num
                end
            end
        end
    end
    return #parts > 0 and table.concat(parts, "  ·  ") or nil
end

local function set_mark(name)
    local r, shot = current_review(), current_shot()
    if not r or review_busy or export.prompting or in_preview(r) then return end
    if not shot or not shot.rung or not shot.num or shot.missing or shot.retired then
        osd("nothing to mark here", 1.5); return
    end
    if notes.mode then osd("select mode: Enter applies, Esc cancels", 1.5); return end
    if notes.step_mark(name) then return end   -- stepping an imported note: its state
    if not notes.on_select(r, shot) then osd("Enter makes this take the select first", 2); return end
    local file = slash(shot.file or shot.play)
    local cur, comp = mark_of(r, shot), notes.comp_of(r, shot)
    local ask   -- open the note box: a state was set (not final: a final has no notes), or comp went on with no state
    if name == "comp" then   -- the switch: flips, and leaves the state alone
        if cur == "final" then osd("a final isn't comped", 1.5); return end
        comp = not comp
        ask = comp and not cur
    else                     -- a state: the same key again clears it; comp stays as it is
        cur = cur ~= name and name or false
        ask = cur and cur ~= "final"
        if cur == "final" then   -- approved: what was asked of it is done with, and an open box goes too
            if notes.box then notes.close(false) end
            r.notes[shot.num] = ""
        end
    end
    r.marks[shot.num] = {file = file, mark = cur or false, comp = comp}
    notes.touch(r, shot.num)
    r.touched[shot.num], r.cleared[shot.num] = true, nil
    if not mp.get_property_bool("pause") then   -- the row is hidden while playing
        local said = cur and MARK_TEXT[cur] or nil
        if comp and cur ~= "final" then said = said and (said .. " + comp") or "comp" end
        osd((shot.label or shot.name) .. "  ·  " .. (said or "state cleared"), 2)
    end
    render(true)
    if ask then notes.edit(shot) end   -- what the room said about it
end
review_click = function(name)   -- a click on the row, or on the green bar's Apply
    if name == "apply" then return notes.mode_apply() end
    if name == "cancel" then return notes.mode_cancel() end
    local pin = name:match("^pin_(%a+)$")
    if pin then return notes.pin(pin) end
    return set_mark(name)
end

-- x: forget the shot's choice. Its entry leaves the choices file on save and the
