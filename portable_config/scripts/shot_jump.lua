local function is_real_video()
    local v = mp.get_property_native("current-tracks/video")
    return v and not v.image and not v.albumart
end

local function select_soundtrack()
    for _, t in ipairs(mp.get_property_native("track-list") or {}) do
        if t.type == "audio" and t.title == SOUNDTRACK_TITLE then
            export.channels = t["demux-channel-count"]
            mp.set_property_number("aid", t.id)
            return
        end
    end
end

mp.register_event("file-loaded", function()
    local path = mp.get_property("path")
    if scan_timer then scan_timer:kill(); scan_timer = nil end
    if scan and scan.path ~= path then stop_scan() end
    state = {path = path}

    local asm = pending_assembly
    pending_assembly = nil
    if asm and asm.url == path then
        state.assembly = asm
        state.shots = asm.shots
        state.fps = asm.fps
        if asm.soundtrack then select_soundtrack() end
        if encoding then add_burn_in(); return end
        bind_quit_keys(true)
        local notes = {}
        if asm.retired > 0 then notes[#notes + 1] = asm.retired .. " rejected" end
        if asm.missing > 0 then notes[#notes + 1] = asm.missing .. " missing" end
        local head = asm.notice or string.format("assembly: %d clips", #asm.shots)
        osd(head .. (#notes > 0 and ("  (" .. table.concat(notes, ", ") .. ")") or ""), 2)
        return
    end

    bind_quit_keys(false)
    if not path or path:find("://", 1, true) or is_xml(path) or not is_real_video() then return end
    if load_sidecar(path) then return end
    if scanned[path] then set_shots_from_cuts(scanned[path]); return end
    if scan and scan.path == path then set_shots_from_cuts(scan.cuts); return end
    if not o.enabled then return end
    -- debounce: flipping through files with UP/DOWN shouldn't spawn a scanner each
    scan_timer = mp.add_timeout(0.3, function()
        scan_timer = nil
        if state.path == path then start_scan(path) end
    end)
end)

